    def test_bootstrap_and_installed_runtime_can_select_and_write_offline(self):
        for scope in ('project','global'):
            target=self.root/scope;home=self.root/'home';aikya_setup.setup(ROOT,target,scope,home=home)
            runtime=target/'.aikya/runtime' if scope=='project' else home/'.claude/aikya-harnes'
            result=subprocess.run([sys.executable,'-B',str(runtime/'documentation_workflows.py'),'plan','--command','aikya-feature','--root',str(target)],cwd=self.tmp.name,capture_output=True,text=True)
            self.assertEqual(2,result.returncode)  # No project profile exists; no invented profile.
            self.assertIn('profile',result.stderr.lower())
        target=self.root/'installed';install.install(target,self.profile(),{'modules':[]})
        payload=target/'reviewed.json';payload.write_text(json.dumps(self.feature()))
        result=subprocess.run([sys.executable,'-B',str(target/'aikya/scripts/harness/documentation_workflows.py'),'write','--command','aikya-feature','--root',str(target),'--slug','lookup','--input',str(payload),'--approved'],cwd=self.tmp.name,capture_output=True,text=True)
        self.assertEqual(0,result.returncode,result.stderr)
        self.assertTrue((target/'aikya/docs/features/lookup/spec.md').is_file())

