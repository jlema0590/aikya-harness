    def test_feature_request_gate_accepts_the_composed_feature_spec(self):
        self.configure();module=self.workflows()
        result=module.write(self.root,'aikya-feature',self.feature(),slug='lookup',approved=True)
        import importlib.util
        spec=runtime_support.module_spec('composed_feature_gate',ROOT/'src/aikya/resources/project_template/scripts/harness/docs_guard.py')
        guard=importlib.util.module_from_spec(spec);spec.loader.exec_module(guard);guard=getattr(guard,'_module',guard);guard.ROOT=self.root
        request='REQ-20261022-01234567';log='aikya/docs/changes/'+request+'.md'
        docs_layout.write_document(self.root,'changes/'+request+'.md',
            '# Feature fixture\n\n## Changes\n\nsrc/lookup.py changed in the fixture.\n\n## Evidence\n\nFixture evidence only.\n\n## Updated documents\n\n'+result['path'])
        state={'request_id':request,'kind':'feature','baseline':{'src/lookup.py':'before'}}
        now={'src/lookup.py':'after',result['path']:'new',log:'new'}
        valid,messages=guard.validate_request(state,now)
        self.assertTrue(valid,messages)
        unchanged={'src/lookup.py':'after',log:'new'}
        valid,messages=guard.validate_request(state,unchanged)
        self.assertFalse(valid,messages)  # An untouched old spec does not cover a new request.

