        with self.assertRaises(ValueError):module.write(self.root,'aikya-tests',payload,document='summary',slug='lookup',approved=True)
        log=self.root/'checks/lookup.log';log.parent.mkdir();log.write_text('Fixture evidence only; no application command executed.')
        result=module.write(self.root,'aikya-tests',payload,document='summary',slug='lookup',approved=True)
        body=(self.root/result['path']).read_text()
