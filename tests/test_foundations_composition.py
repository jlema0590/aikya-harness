class FoundationsCompositionTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup)
        self.root=Path(self.tmp.name)/'project'

    def profile(self,example='next-react',**extra):
        value=json.loads((ROOT/'examples'/example/'answers.json').read_text());value.update(extra)
        return install.validated(value,self.root)

    def configure(self,example='next-react',language='en',**extra):
        self.root.mkdir();profile=self.profile(example,**extra)
        file=self.root/'.harness/project-profile.json';file.parent.mkdir();file.write_text(json.dumps({'decisions':profile}))
        file=self.root/'.aikya/docs-policy.json';file.parent.mkdir();file.write_text(json.dumps({'schema_version':1,'language':language}))
        return profile

    def workflows(self):return importlib.import_module('aikya.documentation.composition')

    def feature(self):
        return {'title':'Missing-record response','objective':'Return a stable response for unknown records.',
                'acceptance':['An unknown fixture ID returns the documented not-found response.'],
                'sections':{'context-and-scope':'Only the existing lookup adapter is affected.','alternatives-considered':'A separate service was rejected due to additional state.'}}

    def test_selector_covers_public_flows_without_enabling_sdd(self):
        module=self.workflows();profile=self.profile()
        for command in ('aikya-init','aikya-analyze','aikya-arc-review','aikya-feature','aikya-bugfix','aikya-tests'):
            result=module.select(profile,command)
            self.assertIn('templates',result);self.assertIn('engine',result)
        with self.assertRaises(ValueError):module.select(profile,'aikya-plan')
        sdd_profile={**profile,'methodology':'sdd'}
        for command in ('aikya-feature','aikya-bugfix','aikya-implement','aikya-plan','aikya-specify','aikya-tasks','aikya-sdd-status'):
            self.assertEqual('sdd',module.select(sdd_profile,command)['engine'])
        self.assertEqual('read_only',module.select(sdd_profile,'aikya-sdd-status')['mode'])
        self.assertEqual('read_only',module.select(profile,'aikya-arc-review')['mode'])

    def test_standard_feature_combines_acceptance_and_foundations_only_when_supplied(self):
        self.configure();module=self.workflows()
        result=module.write(self.root,'aikya-feature',self.feature(),slug='lookup',approved=True)
        file=self.root/result['path'];body=file.read_text()
        self.assertEqual('aikya/docs/features/lookup/spec.md',result['path'])
        for value in ('## Acceptance criteria','AC-01','## Alternatives considered','Only the existing lookup adapter','aikya-template/docs/'):
            self.assertIn(value,body)
        self.assertNotIn('## Rollout and rollback',body)
        self.assertEqual(1,body.splitlines().count(FOOTER))
        self.assertEqual([],docs_layout.validate_layout(self.root))

    def test_acceptance_approval_and_unknown_fields_are_validated_before_writes(self):
        self.configure();module=self.workflows()
        with self.assertRaises(ValueError):module.write(self.root,'aikya-feature',self.feature(),slug='lookup',approved=False)
        for update in ({'acceptance':[]},{'acceptance':['']},{'sections':{'invented':'unsupported'}}):
            with self.assertRaises(ValueError):module.write(self.root,'aikya-feature',{**self.feature(),**update},slug='lookup',approved=True)
        self.assertFalse((self.root/'aikya/docs').exists())

    def test_partial_update_preserves_other_generated_sections_and_code_fences(self):
        self.configure();module=self.workflows()
        result=module.write(self.root,'aikya-feature',self.feature(),slug='lookup',approved=True)
        path=self.root/result['path'];body=docs_layout.content(path.read_text())
        path.write_text(docs_layout.stamp(body+'\n\n## Reviewed legacy note\n\nKeep this evidence.\n\n```md\n## Alternatives considered\nA literal heading inside code.\n```'))
        updated=self.feature();updated['sections']={'context-and-scope':'The same adapter and its focused test are affected.'}
        module.write(self.root,'aikya-feature',updated,slug='lookup',approved=True)
        body=path.read_text()
        self.assertIn('A separate service was rejected',body)
        self.assertIn('Keep this evidence.',body)
        self.assertIn('A literal heading inside code.',body)
        self.assertIn('The same adapter and its focused test',body)

