class MigrationSafetyRegressionTests(unittest.TestCase):
    def seed(self,root,name,text):
        p=root/'aikya/docs'/name;p.parent.mkdir(parents=True,exist_ok=True)
        p.write_text('<!-- GENERATED BY CLAUDE-DEV-HARNESS -->\n'+text)
        return p

    def test_competing_architectures_block_before_any_move(self):
        from aikya.documentation import layout as docs_layout
        with tempfile.TemporaryDirectory() as d:
            root=Path(d)
            a=self.seed(root,'Feature-V1/03.-arquitectura.md','# A\n\nFirst architecture.')
