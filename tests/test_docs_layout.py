class DocumentationLayoutTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup)
        self.root=Path(self.tmp.name)

    def profile(self):
        return install.validated(json.loads((ROOT/'examples/next-react/answers.json').read_text()),self.root)

    def test_generated_templates_have_visible_footer_and_no_leading_legacy_comment(self):
        for lang in ('en','es'):
            with self.subTest(language=lang):
                pages=doc_bootstrap.pages(self.profile(),[],lang)
                self.assertTrue(pages)
                for name,body in pages.items():
                    self.assertTrue(body.rstrip().endswith(FOOTER),name)
                    self.assertNotIn('<!-- GENERATED BY CLAUDE-DEV-HARNESS -->',body,name)

    def test_fresh_install_uses_canonical_layout_without_unrequested_comparison(self):
        install.install(self.root,self.profile(),{'modules':[]},docs_lang='en')
        docs=self.root/'aikya/docs'
        self.assertFalse((docs/'harness').exists())
        self.assertTrue((docs/'architecture/architecture-overview.md').is_file())
        self.assertTrue((docs/'plan/testing.md').is_file())
        self.assertTrue((docs/'tools/agents.md').is_file())
        self.assertTrue((docs/'tools/token-policy.md').is_file())
        self.assertFalse((docs/'tools/skill-comparison.md').exists())
        self.assertFalse((docs/'quality/testing.md').exists())
        self.assertIn('/aikya-scaffold plan',(docs/'overview.md').read_text())
        self.assertTrue((docs/'indice.md').is_file())

    def test_analysis_omits_unsupported_stubs_and_keeps_actual_architecture(self):
        (self.root/'pom.xml').write_text('<project/>')
        preview=execute(self.root,dry_run=True,docs_lang='en',methodology='odd')
        self.assertFalse(preview['writes']);self.assertFalse((self.root/'aikya/docs').exists())
        planned={x['path'] for x in preview['plan']}
        self.assertIn('aikya/docs/architecture/architecture-overview.md',planned)
        self.assertIn('aikya/docs/indice.md',planned)
        self.assertNotIn('aikya/docs/bugs/index.md',planned)
        self.assertNotIn('aikya/docs/harness/bootstrap.md',planned)
        result=execute(self.root,approved=True,docs_lang='en',methodology='odd')
        self.assertEqual('READY',result['status'])
        docs=self.root/'aikya/docs'
        for name in ['bugs/index.md','features/index.md','design/design-system.md','harness/skills-comparison.md','operations/observability.md','plan/testing.md']:
            self.assertFalse((docs/name).exists(),name)
        self.assertTrue((docs/'architecture/architecture-overview.md').is_file())
        self.assertNotIn('bugs/index.md',(docs/'indice.md').read_text())

    def test_feature_writer_routes_lowercase_and_architecture_into_main_directory(self):
        spec=importlib.util.find_spec('docs_layout');self.assertIsNotNone(spec)
        from aikya.documentation import layout as docs_layout
        written=docs_layout.write_document(self.root,'Feature-V2/01.-Scope.md','# Actual feature\n\nApproved user scope.\n')
        self.assertEqual('aikya/docs/features/feature-v2/01.-scope.md',written)
        architecture=docs_layout.write_document(self.root,'features/Feature-V2/03.-arquitectura.md','# Architecture\n\nVerified module boundaries.\n')
        self.assertEqual('aikya/docs/architecture/architecture-overview.md',architecture)
        self.assertFalse((self.root/'aikya/docs/feature-v2').exists())
        index=(self.root/'aikya/docs/indice.md').read_text()
        self.assertIn('features/feature-v2/01.-scope.md',index)
        self.assertIn('architecture/architecture-overview.md',index)

    def test_writer_skips_heading_only_and_rejects_custom_collision_and_symlink(self):
        self.assertIsNotNone(importlib.util.find_spec('docs_layout'))
        from aikya.documentation import layout as docs_layout
        self.assertIsNone(docs_layout.write_document(self.root,'bugs/empty.md','# Empty\n'))
        p=self.root/'aikya/docs/overview.md';p.parent.mkdir(parents=True,exist_ok=True);p.write_text('# Team-owned\n\nPreserve this document.\n')
        with self.assertRaises(ValueError):docs_layout.write_document(self.root,'overview.md','# New\n\nDifferent content.\n')
        target=self.root/'aikya/docs/outside';target.symlink_to(self.root)
        with self.assertRaises(ValueError):docs_layout.write_document(self.root,'outside/foo.md','# Title\n\nDo not write through link.\n')

    def test_explicit_install_alias_is_registered(self):
        from aikya.installation import registration as aikya_setup
        self.assertIn('aikya-install-skill',aikya_setup.BOOTSTRAP_COMMANDS)
        self.assertIn('aikya-install-skill',aikya_setup.BOOTSTRAP_COMMANDS)


class DocumentationMigrationTests(unittest.TestCase):
    def test_managed_legacy_paths_are_backed_up_and_normalized(self):
        from aikya.documentation import layout as docs_layout
        with tempfile.TemporaryDirectory() as d:
            root=Path(d);docs=root/'aikya/docs'
            old={'harness/bootstrap.md':'# Bootstrap\n\nVerified initialization instructions.\n',
                 'harness/token-policy.md':'# Tokens\n\nKeep the current user model by default.\n',
                 'agents.md':'# Agents\n\nActual registered agents.\n',
                 'quality/testing.md':'# Tests\n\nThe team selected unit tests.\n',
                 'Feature-V2/03.-arquitectura.md':'# Architecture\n\nActual API boundaries.\n'}
            for name,body in old.items():
                p=docs/name;p.parent.mkdir(parents=True,exist_ok=True);p.write_text('<!-- GENERATED BY CLAUDE-DEV-HARNESS -->\n'+body)
            planned=docs_layout.migrate(root)
            self.assertTrue(planned);self.assertFalse((docs/'tools').exists())
            docs_layout.migrate(root,approved=True)
            for name in ['overview.md','tools/agents.md','tools/token-policy.md','plan/testing.md','architecture/architecture-overview.md','indice.md']:
                self.assertTrue((docs/name).is_file(),name)
                self.assertTrue((docs/name).read_text().rstrip().endswith(FOOTER),name)
            self.assertFalse((docs/'harness').exists())
            self.assertFalse((docs/'Feature-V2').exists())
            self.assertTrue((root/'.harness/backup-docs-layout/harness/bootstrap.md').is_file())

    def test_custom_destination_blocks_before_moving_source(self):
        from aikya.documentation import layout as docs_layout
        with tempfile.TemporaryDirectory() as d:
            root=Path(d);docs=root/'aikya/docs'
            source=docs/'agents.md';source.parent.mkdir(parents=True);source.write_text('<!-- GENERATED BY CLAUDE-DEV-HARNESS -->\n# Agents\n\nOriginal recorded content.\n')
            dest=docs/'tools/agents.md';dest.parent.mkdir();dest.write_text('# Team agents\n\nDo not replace this.\n')
            with self.assertRaises(ValueError):docs_layout.migrate(root,approved=True)
            self.assertTrue(source.exists());self.assertEqual('# Team agents\n\nDo not replace this.\n',dest.read_text())

    def test_custom_index_blocks_before_migration(self):
        from aikya.documentation import layout as docs_layout
        with tempfile.TemporaryDirectory() as d:
            root=Path(d);docs=root/'aikya/docs';docs.mkdir(parents=True)
            (docs/'agents.md').write_text('<!-- GENERATED BY CLAUDE-DEV-HARNESS -->\n# Agents\n\nExisting content.\n')
            (docs/'indice.md').write_text('# Custom index\n\nOwner-maintained links.\n')
            with self.assertRaises(ValueError):docs_layout.migrate(root,approved=True)
            self.assertTrue((docs/'agents.md').exists())
            self.assertFalse((docs/'tools/agents.md').exists())


class ComparisonGenerationTests(unittest.TestCase):
    def test_only_explicit_install_records_comparison_and_index(self):
        from aikya.catalogs import external as external_skills
        import inspect
        from unittest.mock import patch
        self.assertIn('record_comparison',inspect.signature(external_skills.install_all).parameters)
        with tempfile.TemporaryDirectory() as d:
            root=Path(d);profile={'frontend':'none','mobile':'none'}
            def install_fixture(target):
                folder=target/'.claude/skills/ponytail';folder.mkdir(parents=True,exist_ok=True)
