    def test_overview_preserves_all_absorbed_sources_and_stationary_links(self):
        from aikya.documentation import layout as docs_layout
        with tempfile.TemporaryDirectory() as d:
            root=Path(d)
            self.seed(root,'harness/requirements.md','# Requirements\n\nPython diagnostics recorded.')
