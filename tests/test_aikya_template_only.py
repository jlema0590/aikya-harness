"""New documents and public template discovery must use one external provider."""
import json
from pathlib import Path
import sys
import tempfile
import unittest

ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT))
from aikya.documentation import templates as library
from aikya.documentation import composition as workflows
from aikya.workflows.sdd import templates as sdd_templates
from aikya.documentation import claude as claude_templates
from aikya.documentation import bootstrap as doc_bootstrap
from aikya.installation import facade as install

SOURCE='aikya-template/docs/'
BUG='general-swe/foundations/bug-report'


class AikyaTemplateOnlyTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup)
        self.root=Path(self.tmp.name)
        self.profile=install.validated(json.loads((ROOT/'examples/next-react/answers.json').read_text()),self.root)
        file=self.root/'.harness/project-profile.json';file.parent.mkdir();file.write_text(json.dumps({'decisions':self.profile}))

    def only_aikya_templates(self,body):
        self.assertIn(SOURCE,body)
        for removed in ('spec-coding.dev','docs-md.com','claudecodeguide.dev','claudecode.page'):
            self.assertNotIn(removed,body)
        self.assertEqual('GENERATED BY AIKYA HARNESS',body.rstrip().splitlines()[-1])

    def test_discovery_and_integrity_expose_only_aikya_templates_catalog(self):
        records=library.catalog()
        self.assertEqual(120,len(records))
        for record in records.values():
            self.assertEqual('aikya',record['provider'])
            self.assertTrue(record['source'].startswith(SOURCE))
        self.assertEqual(120,library.validate_catalog()['templates'])
        with self.assertRaises(ValueError):library.show('docs-md/bug-report')

    def test_all_sdd_roles_resolve_to_packaged_aikya_templates_sources(self):
        records=library.catalog()
        for name,item in sdd_templates.catalog().items():
            with self.subTest(name=name):
                self.assertTrue(item['source'].startswith(SOURCE))
                self.assertIn(item['source'],{record['source'] for record in records.values()})
                self.only_aikya_templates(sdd_templates.starter(name))
                self.assertIn(item['source'],sdd_templates.source_note(name))

    def test_feature_output_retains_acceptance_with_only_aikya_templates_reference(self):
        result=workflows.write(self.root,'aikya-feature',{'title':'Synthetic lookup','objective':'Synthetic stable missing-item response.',
            'acceptance':['The synthetic missing-item request returns its specified response.'],
            'sections':{'alternatives-considered':'Synthetic alternative: reuse the current adapter.'}},slug='lookup',approved=True)
        body=(self.root/result['path']).read_text()
        self.only_aikya_templates(body);self.assertIn('AC-01',body)

    def test_aikya_templates_bug_adapter_appends_and_rejects_incomplete_reports(self):
        payload={'id':'BUG-001','title':'Synthetic missing-item crash','sections':{
            'summary':'Synthetic lookup fails.','environment':'Synthetic local fixture.',
            'steps-to-reproduce':'1. Query the missing fixture ID.',
            'expected-result':'Specified missing-item response.','actual-result':'Synthetic exception.'}}
        library.record(self.root,BUG,payload,approved=True)
        path=self.root/'aikya/docs/bugs/bugs.md';before=path.read_bytes()
        with self.assertRaises(ValueError):library.record(self.root,BUG,payload,approved=True)
        self.assertEqual(before,path.read_bytes())
        incomplete={**payload,'id':'BUG-002','sections':{'summary':'Insufficient reproduction.'}}
        with self.assertRaises(ValueError):library.record(self.root,BUG,incomplete,approved=True)
        self.assertEqual(before,path.read_bytes())
        library.record(self.root,BUG,{**payload,'id':'BUG-002'},approved=True)
        body=path.read_text();self.only_aikya_templates(body)
        self.assertIn('BUG-001',body);self.assertIn('BUG-002',body)
        self.assertIn('Steps to reproduce',body)

    def test_new_claude_and_sdd_bootstrap_reference_aikya_templates(self):
        self.only_aikya_templates(claude_templates.render(self.profile,[]))
        pages=doc_bootstrap.pages({**self.profile,'methodology':'sdd'},[],'en')
        self.only_aikya_templates(pages['aikya/docs/specs/README.md'])

    def test_custom_template_consumer_blocks_install_before_any_writes(self):
        target=self.root/'installed'
        install.install(target,self.profile,{'modules':[]},docs_lang='en')
        consumer=target/'aikya/scripts/harness/documentation_templates.py'
        consumer.write_text(consumer.read_text()+'\n# Team-maintained behavior.\n')
        before={p.relative_to(target):p.read_bytes() for p in target.rglob('*') if p.is_file()}
        with self.assertRaisesRegex(ValueError,'template.*review'):
            install.install(target,self.profile,{'modules':[]},docs_lang='en')
        self.assertEqual(before,{p.relative_to(target):p.read_bytes() for p in target.rglob('*') if p.is_file()})


if __name__=='__main__':unittest.main()
