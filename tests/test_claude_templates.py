"""Project instructions must reflect profile decisions, not website example stacks."""
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from aikya.installation import facade as install
from aikya.installation import registration as aikya_setup
from aikya.discovery.analyze import execute

FOOTER='GENERATED BY AIKYA HARNESS'
CASES={'development':'next-react','infrastructure':'infra-terraform-only','devops':'devops-kustomize'}

class ClaudeTemplateTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup)
        self.root=Path(self.tmp.name)/'project'

    def profile(self,example='next-react',**extra):
        raw=json.loads((ROOT/'examples'/example/'answers.json').read_text());raw.update(extra)
        return install.validated(raw,self.root)

    def test_installed_contract_selects_actual_project_type(self):
        for kind,example in CASES.items():
            with self.subTest(kind=kind):
                target=self.root/kind
                install.install(target,self.profile(example),{'modules':[]},docs_lang='es')
                text=(target/'CLAUDE.md').read_text()
                self.assertIn('## '+('DevOps' if kind=='devops' else kind.title())+' contract',text)
                self.assertNotIn('TODO',text)
                self.assertNotIn('Perfil técnico',text)
                self.assertEqual(1,text.splitlines().count(FOOTER))
                self.assertTrue(text.rstrip().endswith(FOOTER))
                self.assertLess(len(text.splitlines()),200)
                for other in set(CASES)-{kind}:self.assertNotIn('## '+('DevOps' if other=='devops' else other.title())+' contract',text)
                if kind!='development':self.assertNotIn('Next.js',text)

    def test_stack_layout_and_sdd_are_selected_without_invented_commands(self):
        from aikya.documentation import claude as templates
        profile=self.profile(backend='python',backend_framework='fastapi',frontend='none',repository_layout='singlerepo',methodology='sdd')
        text=templates.render(profile,[])
        self.assertIn('Python',text);self.assertIn('fastapi',text)
        self.assertIn('## Single repository',text)
        self.assertIn('## SDD workflow',text)
        for unsupported in ('Next.js','Turborepo','npm run build','uv run pytest','Vercel','Poetry','80%','TODO'):
            self.assertNotIn(unsupported,text)
        plain=templates.render(self.profile(methodology='standard',repository_layout='monorepo'),[])
        self.assertNotIn('## SDD workflow',plain)
        self.assertIn('## Monorepo',plain)

    def test_selected_mobile_and_infrastructure_guidance(self):
        from aikya.documentation import claude as templates
        android=templates.render(self.profile('android-kotlin'),[])
        self.assertIn('Android',android);self.assertIn('kotlin',android)
        self.assertNotIn('iOS',android)
        terraform=templates.render(self.profile('infra-terraform-only'),[])
        self.assertIn('Terraform',terraform);self.assertNotIn('Kustomize',terraform)
        devops=templates.render(self.profile('devops-kustomize'),[])
        self.assertIn('Kustomize',devops);self.assertNotIn('Terraform',devops)

    def test_module_paths_are_indicators_and_not_success_claims(self):
        from aikya.documentation import claude as templates
        text=templates.render(self.profile(mode='existing'),[{'role':'backend','technology':'python','path':'services/lookup'}])
        self.assertIn('services/lookup',text)
        self.assertIn('indicators only',text)
        self.assertIn('NOT VERIFIED',text)

    def test_missing_type_asset_fails_before_install_writes(self):
        from aikya.documentation import claude as templates
        with patch.object(templates,'ASSET_ROOT',self.root/'absent'):
            with self.assertRaises(ValueError):install.install(self.root,self.profile(),{'modules':[]})
        self.assertFalse(self.root.exists())

    def test_existing_custom_claude_remains_exact_on_init_and_analysis(self):
        self.root.mkdir();custom=b'# Team instructions\n\nKeep our reviewed local policy.\n'
        (self.root/'CLAUDE.md').write_bytes(custom)
        (self.root/'package.json').write_text(json.dumps({'dependencies':{'next':'1','react':'1'}}))
        preview=execute(self.root,dry_run=True,docs_lang='en',methodology='odd')
        self.assertEqual(custom,(self.root/'CLAUDE.md').read_bytes())
        self.assertEqual('KEEP_EXISTING',next(op['action'] for op in preview['plan'] if op['path']=='CLAUDE.md'))
        execute(self.root,approved=True,docs_lang='en',methodology='odd')
        self.assertEqual(custom,(self.root/'CLAUDE.md').read_bytes())
        install.install(self.root,self.profile(mode='existing'),install.detect_project(self.root),adopt_existing=True)
        self.assertEqual(custom,(self.root/'CLAUDE.md').read_bytes())

    def test_both_bootstrap_scopes_can_render_without_source_repository(self):
        for scope in ('project','global'):
            with self.subTest(scope=scope):
                target=self.root/scope;home=self.root/'home'
                aikya_setup.setup(ROOT,target,scope,home=home)
                runtime=target/'.aikya/runtime' if scope=='project' else home/'.claude/aikya-harnes'
                code="import sys;from pathlib import Path;sys.path.insert(0,sys.argv[1]);import claude_templates as t;print(t.render({'project_type':'devops','repository_layout':'singlerepo','methodology':'standard'},[]))"
                result=subprocess.run([sys.executable,'-B','-c',code,str(runtime)],cwd=self.tmp.name,capture_output=True,text=True)
                self.assertEqual(0,result.returncode,result.stderr)
                self.assertIn('## DevOps contract',result.stdout)
                self.assertTrue(result.stdout.rstrip().endswith(FOOTER))

if __name__=='__main__':unittest.main()
