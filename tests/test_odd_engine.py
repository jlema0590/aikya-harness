"""ODD task records must be resumable and may never authorize SDD work."""
import importlib,importlib.util,json,sys,tempfile,unittest
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT))
class OddEngineTests(unittest.TestCase):
 def setUp(self):
  self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup);self.root=Path(self.tmp.name)
  file=self.root/'.harness/project-profile.json';file.parent.mkdir();file.write_text(json.dumps({'decisions':{'methodology':'odd','project_type':'development'}}))
  self.payload={'title':'Synthetic lookup','objective':'Preserve synthetic missing-item behavior.','acceptance':['Missing IDs return the specified response.'],
   'tasks':[{'id':'TASK-001','description':'Document lookup.','acceptance':['AC-01'],'depends_on':[],'files':['src/lookup.py'],'checks':['synthetic lookup check']},
            {'id':'TASK-002','description':'Review lookup fixture.','acceptance':['AC-01'],'depends_on':['TASK-001'],'files':['tests/test_lookup.py'],'checks':['synthetic review check']}]}
 def mod(self):
  self.assertIsNotNone(importlib.util.find_spec('aikya.workflows.odd'),'Missing durable ODD engine');return importlib.import_module('aikya.workflows.odd')
 def prepare(self):return self.mod().prepare_feature(self.root,'lookup',self.payload,approved=True)
 def evidence(self):
  path=self.root/'checks/fixture.log';path.parent.mkdir(exist_ok=True);path.write_text('Synthetic fixture evidence; no application command executed.');return 'checks/fixture.log'
 def test_small_and_read_only_work_creates_no_feature_artifacts(self):
  m=self.mod();facts={'understood':True,'contained_risk':True,'resumable_from_request_diff':True}
  self.assertEqual('small',m.classify_work(facts)['size']);self.assertEqual('read_only',m.classify_work({**facts,'read_only':True})['size'])
  self.assertEqual('substantial',m.classify_work({**facts,'contained_risk':False})['size'])
  m.prepare_feature(self.root,'lookup',{**self.payload,'facts':facts},approved=True);self.assertFalse((self.root/'aikya/docs/features').exists())
 def test_dependencies_revision_evidence_and_resume_are_enforced(self):
  m=self.mod();prepared=self.prepare();self.assertEqual(1,prepared['revision'])
  with self.assertRaises(ValueError):m.advance_task(self.root,'lookup','TASK-002','done',[self.evidence()],1)
  with self.assertRaises(ValueError):m.advance_task(self.root,'lookup','TASK-001','done',['missing.log'],1)
  result=m.advance_task(self.root,'lookup','TASK-001','done',[self.evidence()],1)
  self.assertEqual('TASK-002',result['next_task']);self.assertEqual(2,result['revision'])
  with self.assertRaises(ValueError):m.advance_task(self.root,'lookup','TASK-002','done',[self.evidence()],1)
  result=m.advance_task(self.root,'lookup','TASK-002','done',[self.evidence()],2)
  self.assertEqual('recorded_complete',result['status']);self.assertFalse(result['independently_executed'])
  self.assertEqual('recorded_complete',m.resume_feature(self.root,'lookup')['status'])
  body=(self.root/'aikya/docs/features/lookup/spec.md').read_text();self.assertIn('aikya-template/docs/',body);self.assertIn('TASK-002',body)
  self.assertEqual(1,body.splitlines().count('GENERATED BY AIKYA HARNESS'))
 def test_custom_document_external_edits_and_evidence_changes_block_before_writes(self):
  m=self.mod();self.prepare();state=self.root/'aikya/docs/features/lookup/state.json';doc=state.with_name('spec.md')
  doc.write_text(doc.read_text().replace('Synthetic lookup','Team edit'))
  before=state.read_bytes()
  with self.assertRaises(ValueError):m.advance_task(self.root,'lookup','TASK-001','done',[self.evidence()],1)
  self.assertEqual(before,state.read_bytes());self.assertEqual('needs_review',m.resume_feature(self.root,'lookup')['status'])
 def test_sdd_unknown_sections_cycles_and_path_escape_create_no_partial_documents(self):
  m=self.mod()
  for change in ({'tasks':[{'id':'TASK-001','description':'Cycle','acceptance':['AC-01'],'depends_on':['TASK-001'],'files':['src/x.py'],'checks':['fixture']}]},
                 {'tasks':[{'id':'TASK-001','description':'Escape','acceptance':['AC-01'],'depends_on':[],'files':['../outside.py'],'checks':['fixture']}]}):
   with self.assertRaises(ValueError):m.prepare_feature(self.root,'lookup',{**self.payload,**change},approved=True)
  self.assertFalse((self.root/'aikya/docs/features/lookup').exists())
  profile=self.root/'.harness/project-profile.json';profile.write_text(json.dumps({'decisions':{'methodology':'sdd','project_type':'development'}}))
  with self.assertRaises(ValueError):self.prepare()
 def test_reopening_task_invalidates_dependent_completion_and_retains_history(self):
  m=self.mod();self.prepare();e=self.evidence();m.advance_task(self.root,'lookup','TASK-001','done',[e],1);m.advance_task(self.root,'lookup','TASK-002','done',[e],2)
  result=m.advance_task(self.root,'lookup','TASK-001','in_progress',[],3)
  self.assertEqual('todo',result['tasks'][1]['status']);self.assertTrue(result['history']);self.assertEqual('in_progress',result['tasks'][0]['status'])
 def test_changed_evidence_requires_explicit_reconciliation_and_invalidates_dependents(self):
  m=self.mod();self.prepare();e=self.evidence();m.advance_task(self.root,'lookup','TASK-001','done',[e],1);m.advance_task(self.root,'lookup','TASK-002','done',[e],2)
  (self.root/e).write_text('Synthetic revised evidence; earlier outcomes are stale.')
  self.assertEqual('needs_review',m.resume_feature(self.root,'lookup')['status'])
  with self.assertRaises(ValueError):m.reconcile_feature(self.root,'lookup',3,approved=False)
  value=m.reconcile_feature(self.root,'lookup',3,approved=True)
  self.assertEqual(4,value['revision']);self.assertEqual(['todo','todo'],[t['status'] for t in value['tasks']]);self.assertTrue(value['history'])
 def test_versioned_dossier_can_progress_after_a_fresh_checkout_without_local_locks(self):
  import shutil
  m=self.mod();self.prepare();shutil.rmtree(self.root/'.harness/state')
  self.assertEqual('in_progress',m.resume_feature(self.root,'lookup')['status'])
  value=m.advance_task(self.root,'lookup','TASK-001','done',[self.evidence()],1)
  self.assertEqual(2,value['revision'])
if __name__=='__main__':unittest.main()
