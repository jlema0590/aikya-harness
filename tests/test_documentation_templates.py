"""Offline reference templates must never become invented living documentation."""
import runtime_support
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT))
from aikya.installation import facade as install; from aikya.documentation import bootstrap as doc_bootstrap; from aikya.installation import registration as aikya_setup; from aikya.documentation import layout as docs_layout
from aikya.discovery.analyze import execute

FOOTER='GENERATED BY AIKYA HARNESS'
ARCH='general-swe/foundations/architecture-overview'
BUG='general-swe/foundations/bug-report'

class DocumentTemplateTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup)
        self.root=Path(self.tmp.name)/'project'

    def profile(self,example='next-react',**extra):
        raw=json.loads((ROOT/'examples'/example/'answers.json').read_text());raw.update(extra)
        return install.validated(raw,self.root)

    def configure(self,kind='development',language='en'):
        self.root.mkdir()
        path=self.root/'.harness/project-profile.json';path.parent.mkdir();path.write_text(json.dumps({'decisions':{'project_type':kind}}))
        path=self.root/'.aikya/docs-policy.json';path.parent.mkdir();path.write_text(json.dumps({'schema_version':1,'language':language}))

    def report(self,ident='BUG-001'):
        return {'id':ident,'title':'Lookup crashes for a missing item','sections':{'summary':'Lookup fails for a missing ID.','environment':'Controlled lookup fixture build 1.','steps-to-reproduce':'1. Request the absent fixture ID.','expected-result':'A documented not-found response.','actual-result':'Unhandled exception in the fixture.'}}

    def test_full_catalog_and_installed_checksums_preserve_mit_provenance(self):
        from aikya.documentation import templates as templates
        catalog=templates.catalog();milk={k:v for k,v in catalog.items() if v['provider']=='aikya'}
        self.assertEqual(120,len(milk));self.assertEqual(30,len([k for k in milk if k.startswith('general-swe/foundations/')]))
        self.assertIn(BUG,catalog)
        manifest=json.loads((templates.LIBRARY/'manifest.json').read_text())
        self.assertEqual('35fc8e29be1f0093b8ef13a9762de67dc99b6882',manifest['commit'])
        self.assertIn('Copyright (c) 2025 Hristo Hristov',(templates.LIBRARY/'docs/LICENSE').read_text())
        for key,record in manifest['files'].items():
            raw=(templates.LIBRARY/key).read_bytes()
            self.assertEqual(record['installed_sha256'],hashlib.sha256(raw).hexdigest(),key)
        body=templates.show(ARCH)
        self.assertIn('Reference template',body)
        self.assertTrue(body.rstrip().endswith(FOOTER))

    def test_architecture_bootstrap_uses_new_path_and_only_recorded_facts(self):
        for kind,example in [('development','next-react'),('infrastructure','infra-terraform-only'),('devops','devops-kustomize')]:
            with self.subTest(kind=kind):
                pages=doc_bootstrap.pages(self.profile(example),[],'en')
                key='aikya/docs/architecture/architecture-overview.md'
                self.assertIn(key,pages)
                self.assertIn(kind,pages[key]);self.assertIn('not verified',pages[key])
                self.assertIn('Aikya reference templates',pages[key])
                self.assertNotIn('99.9%',pages[key]);self.assertNotIn('400ms',pages[key])
                self.assertNotIn('aikya/docs/bugs/bugs.md',pages)
                self.assertNotIn('aikya/docs/architecture/03.-arquitectura.md',pages)

    def test_reviewed_architecture_sections_omit_empty_and_reject_unknown(self):
        from aikya.documentation import templates as templates
        self.configure()
        with self.assertRaises(ValueError):templates.record(self.root,ARCH,{'title':'Architecture','sections':{}},approved=True)
        with self.assertRaises(ValueError):templates.record(self.root,ARCH,{'title':'Architecture','sections':{'invented':'Unsupported claim'}},approved=True)
        templates.record(self.root,ARCH,{'title':'Lookup architecture','sections':{'1-purpose-and-scope':'Lookup owns only read requests.'}},approved=True)
        output=self.root/'aikya/docs/architecture/architecture-overview.md'
        self.assertIn('Lookup owns only read requests.',output.read_text())
        self.assertNotIn('99.9%',output.read_text())
        self.assertEqual([],docs_layout.validate_layout(self.root))

    def test_bug_report_requires_actual_details_and_appends_without_losing_previous(self):
        from aikya.documentation import templates as templates
        self.configure()
        with self.assertRaises(ValueError):templates.record(self.root,BUG,self.report(),approved=False)
        incomplete=self.report();incomplete['sections'].pop('actual-result')
        with self.assertRaises(ValueError):templates.record(self.root,BUG,incomplete,approved=True)
        self.assertFalse((self.root/'aikya/docs/bugs/bugs.md').exists())
        templates.record(self.root,BUG,self.report(),approved=True)
        before=(self.root/'aikya/docs/bugs/bugs.md').read_text()
        with self.assertRaises(ValueError):templates.record(self.root,BUG,self.report(),approved=True)
        self.assertEqual(before,(self.root/'aikya/docs/bugs/bugs.md').read_text())
        templates.record(self.root,BUG,self.report('BUG-002'),approved=True)
        body=(self.root/'aikya/docs/bugs/bugs.md').read_text()
        self.assertIn('BUG-001',body);self.assertIn('BUG-002',body)
        self.assertEqual(1,body.splitlines().count(FOOTER))
        self.assertFalse((self.root/'aikya/docs/bugs/index.md').exists())
        self.assertEqual([],docs_layout.validate_layout(self.root))

    def test_es_headings_require_reviewed_translation_for_generic_sections(self):
        from aikya.documentation import templates as templates
        self.configure(language='es')
        templates.record(self.root,BUG,self.report(),approved=True)
        self.assertIn('Resultado esperado',(self.root/'aikya/docs/bugs/bugs.md').read_text())
        with self.assertRaises(ValueError):templates.record(self.root,ARCH,{'title':'Arquitectura','sections':{'1-purpose-and-scope':'Alcance real.'}},approved=True)
        templates.record(self.root,ARCH,{'title':'Arquitectura','sections':{'1-purpose-and-scope':{'heading':'Propósito y alcance','body':'Alcance real.'}}},approved=True)
        body=(self.root/'aikya/docs/architecture/architecture-overview.md').read_text()
        self.assertIn('## Propósito y alcance',body);self.assertNotIn('## 1. Purpose and scope',body)

    def test_reserved_paths_custom_docs_and_symlinks_are_protected(self):
        from aikya.documentation import templates as templates
        self.configure();payload={'title':'Architecture','sections':{'1-purpose-and-scope':'Observed lookup only.'}}
        for output in ('../outside.md','specs/development/SPEC-001/spec.md','indice.md','tools/token-policy.md','Specs/development/SPEC-001/spec.md','INDICE.md'):
            with self.subTest(output=output):
                with self.assertRaises(ValueError):templates.record(self.root,ARCH,payload,approved=True,output=output)
        path=self.root/'aikya/docs/architecture/architecture-overview.md';path.parent.mkdir(parents=True);path.write_text('# Custom architecture\n\nTeam policy.')
        with self.assertRaises(ValueError):templates.record(self.root,ARCH,payload,approved=True,replace=True)
        self.assertIn('Team policy.',path.read_text())
        path.unlink();path.symlink_to(self.root/'outside.md')
        with self.assertRaises(ValueError):templates.record(self.root,ARCH,payload,approved=True)
        self.assertFalse((self.root/'outside.md').exists())

    def test_domain_templates_do_not_add_new_supported_project_types(self):
        from aikya.documentation import templates as templates
        self.configure(kind='devops')
        self.assertNotIn('web-development/foundations/api-contract',templates.catalog(project_type='devops'))
        key=next(k for k in templates.catalog() if k.startswith('game-development/') and templates.catalog()[k]['sections'])
        section=next(iter(templates.catalog()[key]['sections']))
        with self.assertRaises(ValueError):templates.record(self.root,key,{'title':'Unsupported game scope','sections':{section:'Not a DevOps project.'}},approved=True)
        self.assertEqual(('development','infrastructure','devops'),install.PROJECT_TYPES)

    def test_both_runtime_scopes_include_offline_catalog_and_installed_utility(self):
        for scope in ('global','project'):
            target=self.root/scope;home=self.root/'home';aikya_setup.setup(ROOT,target,scope,home=home)
            runtime=target/'.aikya/runtime' if scope=='project' else home/'.claude/aikya-harnes'
            result=subprocess.run([sys.executable,'-B',str(runtime/'documentation_templates.py'),'catalog'],cwd=self.tmp.name,capture_output=True,text=True)
            self.assertEqual(0,result.returncode,result.stderr)
            self.assertEqual(120,len(json.loads(result.stdout)))
        target=self.root/'installed'
        install.install(target,self.profile(),{'modules':[]})
        engine=target/'aikya/scripts/harness/documentation_templates.py'
        before={p.relative_to(target):p.read_bytes() for p in target.rglob('*') if p.is_file()}
        result=subprocess.run([sys.executable,'-B',str(engine),'show','--template',ARCH],cwd=self.tmp.name,capture_output=True,text=True)
        self.assertEqual(0,result.returncode,result.stderr)
        self.assertEqual(before,{p.relative_to(target):p.read_bytes() for p in target.rglob('*') if p.is_file()})

    def test_managed_architecture_and_bug_migration_has_backup_and_preserves_content(self):
        self.root.mkdir()
        for relative,body in [('architecture/03.-arquitectura.md','# Architecture\n\nObserved lookup boundary.'),('bugs/index.md','# Bugs\n\nBUG-001: observed fixture crash.')]:
            path=self.root/'aikya/docs'/relative;path.parent.mkdir(parents=True,exist_ok=True);path.write_text(docs_layout.stamp(body))
        docs_layout.migrate(self.root,approved=True)
        for relative in ('architecture/architecture-overview.md','bugs/bugs.md'):
            self.assertTrue((self.root/'aikya/docs'/relative).is_file())
        self.assertIn('Observed lookup boundary.',(self.root/'aikya/docs/architecture/architecture-overview.md').read_text())
        self.assertTrue((self.root/'.harness/backup-docs-layout/architecture/03.-arquitectura.md').is_file())
        self.assertEqual([],docs_layout.validate_layout(self.root))

    def test_migrated_table_bug_identifiers_cannot_be_reused(self):
        from aikya.documentation import templates as templates
        self.configure()
        old=self.root/'aikya/docs/bugs/index.md';old.parent.mkdir(parents=True)
        old.write_text(docs_layout.stamp('# Historical bugs\n\n| ID | Summary |\n|---|---|\n| BUG-001 | Existing observed crash |'))
        docs_layout.migrate(self.root,approved=True)
        path=self.root/'aikya/docs/bugs/bugs.md';before=path.read_bytes()
        with self.assertRaises(ValueError):templates.record(self.root,BUG,self.report(),approved=True)
        self.assertEqual(before,path.read_bytes())

    def test_bug_request_gate_accepts_the_recorded_new_register_path(self):
        from aikya.documentation import templates as templates
        import importlib.util
        spec=runtime_support.module_spec('template_bug_gate',ROOT/'src/aikya/resources/project_template/scripts/harness/docs_guard.py')
        guard=importlib.util.module_from_spec(spec);spec.loader.exec_module(guard);guard=getattr(guard,'_module',guard)
        self.configure();guard.ROOT=self.root
        templates.record(self.root,BUG,self.report(),approved=True)
        request='REQ-20261022-01234567';log='aikya/docs/changes/'+request+'.md'
        docs_layout.write_document(self.root,'changes/'+request+'.md',
            '# Controlled bug fixture\n\n## Changes\n\nsrc/lookup.py was changed in this fixture.\n\n## Evidence\n\nFixture evidence only.\n\n## Updated documents\n\naikya/docs/bugs/bugs.md records the observed failure.')
        state={'request_id':request,'kind':'bug','baseline':{'src/lookup.py':'before'}}
        now={'src/lookup.py':'after','aikya/docs/bugs/bugs.md':'new',log:'new'}
        valid,messages=guard.validate_request(state,now)
        self.assertTrue(valid,messages)

