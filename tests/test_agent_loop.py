"""Agent output cannot override process checks, scope, approvals or limits."""
import importlib,importlib.util,json,sys,tempfile,unittest
from pathlib import Path
from agent_loop_support import project,config,runtime
class AgentLoopTests(unittest.TestCase):
 def setUp(self):
  self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup);self.root=project(self.tmp.name)
 def engine(self):
  self.assertIsNotNone(importlib.util.find_spec('aikya.core.loop'),'Missing bounded task controller');return importlib.import_module('aikya.core.loop')
 def test_scoped_edit_checks_and_distinct_review_complete_the_recorded_task(self):
  m=self.engine();result=m.run(self.root,config(),runtime(),approved=True)
  self.assertEqual('completed',result['status']);self.assertEqual(1,result['iteration']);self.assertEqual('VALUE = 1\n',(self.root/'src/value.py').read_text())
  from aikya.workflows import odd as odd_engine
  self.assertEqual('done',odd_engine.load(self.root,'value')['tasks'][0]['status'])
  folder=self.root/'aikya/docs/loops'/result['run_id'];self.assertTrue((folder/'state.json').is_file());self.assertTrue((folder/'evidence.json').is_file());self.assertTrue((folder/'summary.md').read_text().endswith('GENERATED BY AIKYA HARNESS\n'))
  self.assertIn('loops/'+result['run_id']+'/summary.md',(self.root/'aikya/docs/indice.md').read_text())
 def test_model_claim_of_done_never_overrides_failed_checks_and_stops_without_progress(self):
  result=self.engine().run(self.root,config(),runtime('claim'),approved=True)
  self.assertEqual('blocked',result['status']);self.assertEqual(2,result['iteration']);self.assertEqual('no_progress',result['reason'])
  from aikya.workflows import odd as odd_engine
  self.assertEqual('todo',odd_engine.load(self.root,'value')['tasks'][0]['status'])
 def test_missing_approval_or_unknown_config_writes_nothing(self):
  m=self.engine();before={p:p.read_bytes() for p in self.root.rglob('*') if p.is_file()}
  for raw,approved in ((config(),False),({**config(),'permission_mode':'bypassPermissions'},True)):
   with self.assertRaises(ValueError):m.run(self.root,raw,runtime(),approved=approved)
  self.assertEqual(before,{p:p.read_bytes() for p in self.root.rglob('*') if p.is_file()})
 def test_path_escape_and_readonly_commands_cannot_launch_a_runtime(self):
  m=self.engine()
  for raw in ({**config(),'files':['../outside.txt']},{**config(),'command':'aikya-arc-review'},{**config(),'files':['.env']},{**config(),'files':['aikya/docs/features/value/state.json']}):
   with self.assertRaises(ValueError):m.run(self.root,raw,runtime(),approved=True)
  self.assertFalse((self.root/'aikya/docs/loops').exists())
 def test_denied_tool_and_missing_usage_stop_instead_of_retrying(self):
  m=self.engine()
  for mode,expected in (('escape','permission_required'),('unknown_usage','usage_unavailable')):
   with self.subTest(mode=mode):
    result=m.run(self.root,config(),runtime(mode),approved=True)
    self.assertEqual(expected,result['reason']);self.assertEqual(1,result['iteration'])
  self.assertFalse((self.root.parent/'outside.txt').exists())
 def test_checks_modifying_the_candidate_cannot_certify_it(self):
  raw=config();raw['checks'][0]['argv']=[sys.executable,'-c',"from pathlib import Path;Path('src/value.py').write_text('VALUE = 2\\n')"]
  result=self.engine().run(self.root,raw,runtime(),approved=True)
  self.assertEqual('candidate_changed',result['reason']);self.assertNotEqual('completed',result['status'])
 def test_review_rejection_and_iteration_cap_preserve_unfinished_task(self):
  raw={**config(),'max_iterations':1};result=self.engine().run(self.root,raw,runtime('reject'),approved=True)
  self.assertEqual('iteration_limit',result['reason']);self.assertNotEqual('completed',result['status'])

if __name__=='__main__':unittest.main()
