class LegacyGuideSymlinkSafetyTests(unittest.TestCase):
    def test_legacy_guide_upgrade_never_writes_through_file_or_parent_symlinks(self):
        for parent_link in (False,True):
            with self.subTest(parent_link=parent_link),tempfile.TemporaryDirectory() as d:
                base=Path(d);root=base/'project';root.mkdir();outside=base/'outside';outside.mkdir()
                body=b'# Legacy guide\n\nExact original guidance.\n'
                original=outside/'README.md';original.write_bytes(body)
                destination=root/'infra/docker/README.md'
                if parent_link:
                    destination.parent.parent.mkdir();destination.parent.symlink_to(outside,target_is_directory=True)
                else:
                    destination.parent.mkdir(parents=True);destination.symlink_to(original)
                with self.assertRaises(ValueError):
                    install.upgrade_exact_markdown_source(root,body,destination,[])
                self.assertEqual(body,original.read_bytes())
                self.assertFalse((root/'.harness').exists())

