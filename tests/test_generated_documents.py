FOOTER = 'GENERATED BY AIKYA HARNESS'


class GeneratedDocumentTests(unittest.TestCase):
    def profile(self, root):
        data = json.loads((ROOT/'examples/next-react/answers.json').read_text())
        data['repository_layout'] = 'monorepo'
        return install.validated(data, root)

    def assert_footers(self, root):
        paths = sorted(root.rglob('*.md'))
        self.assertTrue(paths)
        for path in paths:
            with self.subTest(path=path.relative_to(root).as_posix()):
                text = path.read_text(encoding='utf8')
                self.assertTrue(text.rstrip().endswith(FOOTER), str(path))
                self.assertEqual(1, text.splitlines().count(FOOTER), str(path))

    def test_init_marks_every_generated_markdown_including_instructions_and_infra(self):
        with tempfile.TemporaryDirectory() as d:
            root = Path(d)
            install.install(root, self.profile(root), {'modules': []}, docs_lang='en')
            self.assertTrue((root/'CLAUDE.md').is_file())
            self.assertTrue((root/'infra/docker/README.md').is_file())
            self.assertTrue((root/'apps/README.md').is_file())
            self.assert_footers(root)
            before = {p.relative_to(root):p.read_bytes() for p in root.rglob('*.md')}
            install.install(root, self.profile(root), {'modules': []}, docs_lang='en')
            self.assertEqual(before, {p.relative_to(root):p.read_bytes() for p in root.rglob('*.md')})

    def test_analysis_marks_report_and_manifest_hashes_actual_stamped_bytes(self):
        with tempfile.TemporaryDirectory() as d:
            root = Path(d)
            (root/'pom.xml').write_text('<project/>')
            result = execute(root, approved=True,methodology='odd')
            self.assertEqual('READY', result['status'])
            self.assert_footers(root)
            report = root/'.aikya/analysis/report.md'
            manifest = json.loads((root/'.aikya/analysis/manifest.json').read_text())
            self.assertEqual(hashlib.sha256(report.read_bytes()).hexdigest(),
                             manifest['managed_paths']['.aikya/analysis/report.md'])
            old = report.read_bytes()
            self.assertEqual('READY', execute(root, approved=True, refresh=True,methodology='odd')['status'])
            self.assertEqual(old, report.read_bytes())

    def test_project_and_global_registration_stamp_assets_and_remain_idempotent(self):
        for scope in ('project','global'):
            with self.subTest(scope=scope), tempfile.TemporaryDirectory() as d:
                root=Path(d);target=root/'project';target.mkdir();home=root/'home';home.mkdir()
                aikya_setup.setup(ROOT,target,scope,home=home)
                self.assert_footers(root)
                runtime=home/'.claude/aikya-harnes' if scope=='global' else target/'.aikya/runtime'
                manifest=json.loads((runtime/'manifest.json').read_text())
                for path in runtime.rglob('*.md'):
                    self.assertEqual(hashlib.sha256(path.read_bytes()).hexdigest(),
                                     manifest['files'][path.relative_to(runtime).as_posix()])
                before={p.relative_to(root):p.read_bytes() for p in root.rglob('*.md')}
                aikya_setup.setup(ROOT,target,scope,home=home)
                self.assertEqual(before,{p.relative_to(root):p.read_bytes() for p in root.rglob('*.md')})

    def test_infrastructure_generator_marks_readmes_without_changing_code_formats(self):
        spec=runtime_support.module_spec('aikya_footer_infra',ROOT/'src/aikya/resources/project_template/scripts/harness/infrastructure.py')
        module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module);module=getattr(module,'_module',module)
        with tempfile.TemporaryDirectory() as d:
            root=Path(d)
            data=json.loads((ROOT/'examples/next-react-terraform-helm/answers.json').read_text())
            profile=install.validated(data,root)
            self.assertEqual(0,module.generate(root,profile,approved=True)[0])
            self.assert_footers(root)
            self.assertNotIn(FOOTER,(root/'infra/terraform/versions.tf').read_text())
            self.assertTrue(module.plan(root,profile).rstrip().endswith(FOOTER))

    def test_generated_markdown_renderers_return_finished_documents(self):
        with tempfile.TemporaryDirectory() as d:
            root=Path(d);profile=self.profile(root)
            for name,body in doc_bootstrap.infra_files(profile).items():
                if name.endswith('.md'):
                    with self.subTest(path=name):self.assertTrue(body.rstrip().endswith(FOOTER))
            from aikya.catalogs import skills as skills_registry
            for locale in ('en','es'):
                with self.subTest(renderer='skills_registry',locale=locale):
                    self.assertTrue(skills_registry.render(root,profile,locale).rstrip().endswith(FOOTER))
            self.assertTrue(install.context_markdown(profile,[]).rstrip().endswith(FOOTER))
            self.assertTrue(install.project_bootstrap_en(profile).rstrip().endswith(FOOTER))
            self.assertTrue(install.project_bootstrap(profile).rstrip().endswith(FOOTER))

    def test_universal_footer_does_not_claim_or_overwrite_custom_documents(self):
        with tempfile.TemporaryDirectory() as d:
            root=Path(d);custom='# Team instructions\n\nKeep these instructions.\n'
            (root/'CLAUDE.md').write_text(custom)
            install.install(root,self.profile(root),{'modules':[]})
            self.assertEqual(custom,(root/'CLAUDE.md').read_text())




