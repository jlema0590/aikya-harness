"""Typed reference memories cannot grant approvals or exceed recall budgets."""
import importlib,importlib.util,tempfile,time,unittest
from pathlib import Path
from agent_loop_support import project
class MemoryTests(unittest.TestCase):
 def module(self):
  self.assertIsNotNone(importlib.util.find_spec('aikya.memory.knowledge'),'Missing selective project memories');return importlib.import_module('aikya.memory.knowledge')
 def test_recall_is_budgeted_current_and_isolated_between_projects(self):
  m=self.module()
  with tempfile.TemporaryDirectory() as tmp:
   root=project(tmp);note=m.remember(root,{'kind':'feedback','text':'Value must equal one for this lookup.','source':'src/value.py','ttl_days':30},approved=True)
   self.assertLessEqual(len(m.recall(root,'value lookup',45)),45);self.assertIn('Value must equal one',m.recall(root,'value lookup',1000))
   other=Path(tmp)/'other';other.mkdir();self.assertEqual('',m.recall(other,'value lookup',1000))
   (root/'src/value.py').write_text('VALUE = 2\n');self.assertEqual('',m.recall(root,'value lookup',1000))
   self.assertTrue((root/note).read_text().endswith('GENERATED BY AIKYA HARNESS\n'))
 def test_approval_scope_unknown_fields_and_expired_notes_are_rejected_or_ignored(self):
  m=self.module()
  with tempfile.TemporaryDirectory() as tmp:
   root=project(tmp);raw={'kind':'project','text':'Lookup uses a stable key.','source':'src/value.py','ttl_days':1}
   with self.assertRaises(ValueError):m.remember(root,raw,approved=False)
   with self.assertRaises(ValueError):m.remember(root,{**raw,'approved':True},approved=True)
   m.remember(root,raw,approved=True,now=1);self.assertEqual('',m.recall(root,'lookup stable',1000,now=86402))
 def test_duplicate_notes_are_not_multiplied_and_custom_edits_are_preserved(self):
  m=self.module()
  with tempfile.TemporaryDirectory() as tmp:
   root=project(tmp);raw={'kind':'reference','text':'Use a stable value.','source':'src/value.py','ttl_days':30}
   one=m.remember(root,raw,approved=True);two=m.remember(root,raw,approved=True);self.assertEqual(one,two)
   p=root/one;p.write_text('Team custom note\n')
   with self.assertRaises(ValueError):m.remember(root,raw,approved=True)
   self.assertEqual('Team custom note\n',p.read_text())

class MemoryMalformedTests(unittest.TestCase):
 def test_nan_memory_times_are_rejected_instead_of_becoming_immortal(self):
  from aikya.memory import knowledge as agent_memory
  with tempfile.TemporaryDirectory() as tmp:
   root=project(tmp)
   with self.assertRaises(ValueError):agent_memory.remember(root,{'kind':'project','text':'Value lookup policy.','source':'src/value.py','ttl_days':1},approved=True,now=float('nan'))

if __name__=='__main__':unittest.main()
