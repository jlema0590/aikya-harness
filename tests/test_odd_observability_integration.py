"""Offline onboarding matrix: 3 project types × 2 methods × 2 locales × 2 scopes."""
import json,os,subprocess,sys,tempfile,unittest
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT))
from aikya.installation.registration import setup
from aikya.core import state as execution_state
class OnboardingMatrixTests(unittest.TestCase):
 def test_new_and_existing_projects_keep_the_explicit_method_and_real_phase_outcomes(self):
  examples={'development':'next-react','infrastructure':'infra-terraform-only','devops':'devops-kustomize'}
  with tempfile.TemporaryDirectory() as tmp:
   base=Path(tmp)
   for kind,example in examples.items():
    for method in ('odd','sdd'):
     for locale in ('en','es'):
      for scope in ('global','project'):
       for mode in ('new','existing'):
        with self.subTest(kind=kind,method=method,locale=locale,scope=scope,mode=mode):
         folder=base/'-'.join((kind,method,locale,scope,mode));root=folder/'project';root.mkdir(parents=True);home=folder/'home';cache=folder/'cache'
         if mode=='existing':
          path=root/({'development':'pom.xml','infrastructure':'main.tf','devops':'kustomization.yaml'}[kind]);path.write_text({'development':'<project/>','infrastructure':'terraform {}\n','devops':'resources: []\n'}[kind])
         setup(ROOT,root,scope,home=home)
         runtime=home/'.claude/aikya-harnes' if scope=='global' else root/'.aikya/runtime'
         args=['init' if mode=='new' else 'analyze','--target',str(root),'--methodology',method,'--docs-lang',locale,'--session','matrix']
         if mode=='new':
          answers=folder/'answers.json';answers.write_bytes((ROOT/'examples'/example/'answers.json').read_bytes());args+=['--answers',str(answers),'--external','skip']
         else:args+=['--approved']
         env={**os.environ,'AIKYA_EXECUTION_CACHE':str(cache),'PYTHONDONTWRITEBYTECODE':'1'}
         proc=subprocess.run([sys.executable,'-B',str(runtime/'aikya_cli.py'),*args],capture_output=True,text=True,env=env)
         self.assertEqual(0,proc.returncode,proc.stderr+'\n'+proc.stdout[-1500:])
         profile=json.loads((root/'.harness/project-profile.json').read_text())['decisions'];self.assertEqual(method,profile['methodology']);self.assertEqual(kind,profile['project_type'])
         run=execution_state.read_active({'root':str(root),'session_id':'matrix','cache_root':str(cache)})
         self.assertEqual('completed',run['status'],run.get('reason'));self.assertEqual('completed',run['phases']['security']['status']);self.assertEqual('skipped',run['phases']['review']['status'])
         self.assertEqual(locale,json.loads((root/'.aikya/docs-policy.json').read_text())['language'])
         for path in (root/'aikya/docs').rglob('*.md'):self.assertEqual(1,path.read_text().splitlines().count('GENERATED BY AIKYA HARNESS'),str(path))
if __name__=='__main__':unittest.main()
