"""The viewer is a bounded projection, never a note approval or remote client."""
import importlib.util
import hashlib
import json
from pathlib import Path
import re
import tempfile
import shutil
import unittest
from unittest.mock import patch


class MemoryViewerTests(unittest.TestCase):
    def setUp(self):
        self.assertIsNotNone(importlib.util.find_spec('aikya.memory.viewer'), 'Memory viewer is missing')
        from aikya.memory.viewer.collect import collect_snapshot
        from aikya.memory.viewer.export import export_view
        from aikya.memory.viewer.contracts import ViewerOptions
        from aikya.code_index.policy import configure
        self.collect, self.export, self.Options = collect_snapshot, export_view, ViewerOptions
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name).resolve()
        configure(self.root, approved=True)
        (self.root / 'model.py').write_text('class Order:\n    def save(self):\n        pass\n')

    def test_export_contains_verified_symbols_and_report_matches_html(self):
        result = self.export(self.root, refresh=True)
        self.assertEqual('complete', result.status)
        raw = (self.root / result.html_path).read_bytes()
        html = raw.decode('utf8')
        report = (self.root / result.report_path).read_text(encoding='utf8')
        self.assertIn(hashlib.sha256(raw).hexdigest(), report)
        payload = json.loads(re.search(r'<script type="application/json" id="snapshot">(.*?)</script>', html, re.S)[1])
        self.assertIn('Order.save', {n['label'] for n in payload['nodes']})
        self.assertNotIn(str(self.root), html)
        self.assertTrue(report.endswith('GENERATED BY AIKYA HARNESS\n'))
        self.assertIn('memory/view/report.md', (self.root / 'aikya/docs/indice.md').read_text(encoding='utf8'))

    def test_export_does_not_rewrite_unchanged_files_or_include_itself(self):
        first = self.export(self.root, refresh=True)
        path = self.root / first.html_path
        before = path.stat().st_mtime_ns
        second = self.export(self.root, refresh=True)
        self.assertEqual(before, path.stat().st_mtime_ns)
        self.assertEqual(first.published_generation, second.published_generation)
        snapshot = self.collect(self.root)
        self.assertFalse(any('memory/view/' in n.get('path', '') or n.get('path') == 'aikya/docs/indice.md' for n in snapshot.nodes))

    def test_layout_asset_update_republishes_matching_pair_without_data_changes(self):
        from aikya.memory.viewer import render
        from aikya.memory.viewer.publication import read_publication
        assets = tempfile.TemporaryDirectory()
        self.addCleanup(assets.cleanup)
        resources = Path(assets.name) / 'renderer'
        shutil.copytree(Path(render.__file__).resolve().parents[2] / 'resources/memory-viewer', resources)
        with patch.object(render, 'RESOURCES', resources, create=True):
            first = self.export(self.root, refresh=True)
            asset = resources / 'layout.js'
            asset.write_text(asset.read_text() + '\n/* new layout revision */\n')
            second = self.export(self.root)
            self.assertNotEqual(first.published_generation, second.published_generation)
            snapshot, generation = read_publication(self.root)
            self.assertEqual(second.published_generation, generation)
            raw = (self.root / second.html_path).read_bytes()
            html = raw.decode('utf8')
            self.assertIn('new layout revision', html)
            script = re.search(r'<script>(.*?)</script>', html, re.S)[1]
            import base64
            digest = base64.b64encode(hashlib.sha256(script.encode()).digest()).decode()
            self.assertIn("'sha256-" + digest + "'", html)
            self.assertIn(hashlib.sha256(raw).hexdigest(), (self.root / second.report_path).read_text())
            before = (self.root / second.html_path).stat().st_mtime_ns
            self.export(self.root)
            self.assertEqual(before, (self.root / second.html_path).stat().st_mtime_ns)

    def test_dry_run_never_writes_and_rejects_refresh(self):
        before = {p.relative_to(self.root): p.read_bytes() for p in self.root.rglob('*') if p.is_file()}
        result = self.export(self.root, dry_run=True)
        self.assertEqual('preview', result.status)
        self.assertEqual(before, {p.relative_to(self.root): p.read_bytes() for p in self.root.rglob('*') if p.is_file()})
        with self.assertRaises(ValueError):
            self.export(self.root, dry_run=True, refresh=True)

    def test_unreviewed_expired_and_changed_source_notes_keep_their_own_states(self):
        from aikya.memory.knowledge import propose, remember
        pending = propose(self.root, {'kind': 'reference', 'text': 'Pending order rule', 'source': 'model.py', 'ttl_days': 1}, now=100)
        approved = remember(self.root, {'kind': 'project', 'text': 'Approved order rule', 'source': 'model.py', 'ttl_days': 10}, approved=True, now=100)
        raw = (self.root / approved).read_bytes()
        snapshot = self.collect(self.root, now=200)
        notes = [n for n in snapshot.nodes if n['type'] == 'memory']
        self.assertEqual({'pending', 'approved'}, {n['details']['review_state'] for n in notes})
        self.assertEqual(1, sum(n['details']['eligible_for_recall'] for n in notes))
        (self.root / 'model.py').write_text('class NewOrder: pass\n')
        snapshot = self.collect(self.root, now=90000)
        notes = [n for n in snapshot.nodes if n['type'] == 'memory']
        self.assertTrue(all(not n['details']['eligible_for_recall'] for n in notes))
        self.assertTrue(all(n['details']['source_status'] == 'changed' for n in notes))
        self.assertEqual(raw, (self.root / approved).read_bytes())
        self.assertEqual('pending', next(n['details']['review_state'] for n in notes if n['path'] == pending))

    def test_more_than_recall_limit_are_visible_without_private_store_access(self):
        from aikya.memory.knowledge import propose
        for n in range(12):
            propose(self.root, {'kind': 'reference', 'text': 'Rule ' + str(n), 'source': 'model.py', 'ttl_days': 1}, now=100)
        with patch('aikya.memory.store.store_root', side_effect=AssertionError('Must not inspect private/global stores')):
            snapshot = self.collect(self.root, now=200)
        self.assertEqual(12, sum(n['type'] == 'memory' for n in snapshot.nodes))

    def test_hostile_document_text_remains_inert_inside_embedded_json(self):
        from aikya.documentation.layout import write_document
        write_document(self.root, 'features/hostile.md', '# </script><script>alert(1)</script>\n\n[unsafe](javascript:alert(1))')
        result = self.export(self.root, refresh=True)
        html = (self.root / result.html_path).read_text(encoding='utf8')
        self.assertNotIn('</script><script>alert(1)</script>', html)
        self.assertIn("connect-src 'none'", html)
        self.assertNotIn('https://', html)
        self.assertEqual(2, len(re.findall(r'<script(?:\s|>)', html)))

    def test_missing_or_disabled_index_does_not_get_enabled_by_export(self):
        policy = self.root / '.aikya/code-index.json'
        value = json.loads(policy.read_text(encoding='utf8'));value['enabled'] = False
        policy.write_text(json.dumps(value))
        result = self.export(self.root)
        self.assertIn(result.status, ('complete', 'partial'))
        self.assertFalse((self.root / '.harness/state/code-index').exists())
        self.assertFalse(json.loads(policy.read_text(encoding='utf8'))['enabled'])
        with self.assertRaises(ValueError):
            self.export(self.root, refresh=True)

    def test_custom_destinations_and_symlinks_are_never_replaced(self):
        target = self.root / 'aikya/docs/memory/view/index.html'
        target.parent.mkdir(parents=True)
        target.write_text('<p>Team report</p>')
        with self.assertRaises(ValueError):
            self.export(self.root, refresh=True)
        self.assertEqual('<p>Team report</p>', target.read_text(encoding='utf8'))
        target.unlink()
        outside = self.root / 'outside.html';outside.write_text('Keep me')
        target.symlink_to(outside)
        with self.assertRaises(ValueError):
            self.export(self.root, refresh=True)
        self.assertEqual('Keep me', outside.read_text(encoding='utf8'))

    def test_limits_report_omissions_and_never_mutate_source_documents(self):
        from aikya.documentation.layout import write_document
        for n in range(3):
            write_document(self.root, 'features/doc-' + str(n) + '.md', '# Rule ' + str(n) + '\n\nDocumented acceptance rule.')
        snapshot = self.collect(self.root, options=self.Options(max_documents=1))
        self.assertEqual('partial', snapshot.coverage['documents'])
        self.assertEqual(1, sum(n['type'] == 'document' for n in snapshot.nodes))
        self.assertTrue((self.root / 'aikya/docs/features/doc-2.md').exists())

    def test_edits_to_owned_html_are_preserved_and_require_review(self):
        result = self.export(self.root, refresh=True)
        target = self.root / result.html_path
        customized = target.read_text(encoding='utf8').replace('<title>Aikya Memory</title>', '<title>Team memory</title>')
        target.write_text(customized, encoding='utf8')
        with self.assertRaises(ValueError):
            self.export(self.root, refresh=True)
        self.assertEqual(customized, target.read_text(encoding='utf8'))

    def test_note_inspection_has_a_cumulative_input_budget(self):
        from aikya.memory.knowledge import propose, inspect_notes
        for n in range(3):
            propose(self.root, {'kind': 'reference', 'text': 'Bounded rule ' + str(n), 'source': 'model.py', 'ttl_days': 1}, now=100)
        result = inspect_notes(self.root, now=200, max_input_bytes=1000)
        self.assertGreater(result.omitted_count, 0)
        self.assertLess(len(result.notes), 3)

    def test_interrupted_publication_recovers_without_serving_mismatched_data(self):
        from aikya.memory.viewer.publication import read_publication
        self.export(self.root, refresh=True)
        (self.root / 'model.py').write_text('class Changed: pass\n')
        with patch('aikya.memory.viewer.export.write_document', side_effect=OSError('Interrupted report write')):
            with self.assertRaises(OSError):
                self.export(self.root, refresh=True)
        with self.assertRaises(ValueError):
            read_publication(self.root)
        result = self.export(self.root, refresh=True)
        snapshot, generation = read_publication(self.root)
        self.assertEqual(result.published_generation, generation)
        self.assertIn('Changed', {node['label'] for node in snapshot.nodes})

    def test_serialized_budget_counts_html_safe_json_expansion(self):
        from aikya.documentation.layout import write_document
        from aikya.memory.viewer.render import render_html
        write_document(self.root, 'features/encoded.md', '# Encoded budget\n\n' + '<' * 1000)
        snapshot = self.collect(self.root, options=self.Options(max_serialized_bytes=5000))
        html = render_html(snapshot)
        payload = re.search(r'<script type="application/json" id="snapshot">(.*?)</script>', html, re.S)[1]
        self.assertLessEqual(len(payload.encode('utf8')), 5000)
        self.assertIn('serialized_limit', snapshot.diagnostics)
        with self.assertRaises(ValueError):
            self.collect(self.root, options=self.Options(max_serialized_bytes=1))


if __name__ == '__main__':
    unittest.main()
