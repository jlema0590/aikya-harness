"""Installed onboarding and conservative retirement of the historical gallery."""
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from aikya.installation import registration as aikya_setup

GALLERY = 'examples/documentation/generated'


class RuntimePayloadTests(unittest.TestCase):
    def test_registered_runtime_runs_all_onboarding_profiles_without_source_gallery(self):
        with tempfile.TemporaryDirectory() as temporary:
            base = Path(temporary)
            unrelated = base / 'unrelated'
            unrelated.mkdir()
            for scope in ('global', 'project'):
                registered = base / scope
                home = base / (scope + '-home')
                aikya_setup.setup(ROOT, registered, scope, home=home)
                runtime = home / '.claude/aikya-harnes' if scope == 'global' else registered / '.aikya/runtime'
                self.assertFalse((runtime / GALLERY).exists())
                guide = (runtime / 'examples/documentation/README.md').read_text()
                self.assertNotIn('](generated/README.es.md)', guide)
                self.assertIn('https://github.com/jlema0590/aikya-harness/', guide)
                self.assertTrue((runtime / 'aikya-template/manifest.json').is_file())
                for kind, fixture in (('development', 'next-react'), ('infrastructure', 'infra-terraform-only'), ('devops', 'devops-docker-compose')):
                    for method in ('odd', 'sdd'):
                        for locale in ('en', 'es'):
                            for command in ('init', 'analyze'):
                                with self.subTest(scope=scope, kind=kind, method=method, locale=locale, command=command):
                                    case = base / '-'.join((scope, kind, method, locale, command))
                                    target = case / 'project'
                                    target.mkdir(parents=True)
                                    arguments = [command, '--target', str(target), '--methodology', method, '--docs-lang', locale]
                                    if command == 'init':
                                        answers = case / 'answers.json'
                                        answers.write_bytes((ROOT / 'examples' / fixture / 'answers.json').read_bytes())
                                        arguments += ['--answers', str(answers), '--external', 'skip']
                                    else:
                                        marker, body = {'development': ('pom.xml', '<project/>'), 'infrastructure': ('main.tf', 'terraform {}\n'), 'devops': ('compose.yaml', 'services:\n  api:\n    image: example/api:1\n')}[kind]
                                        (target / marker).write_text(body)
                                        arguments += ['--approved']
                                    result = subprocess.run([sys.executable, '-B', str(runtime / 'aikya_cli.py'), *arguments], cwd=unrelated, env={**os.environ, 'PYTHONPATH': '', 'PYTHONDONTWRITEBYTECODE': '1', 'AIKYA_EXECUTION_CACHE': str(case / 'cache')}, capture_output=True, text=True, timeout=60)
                                    self.assertEqual(0, result.returncode, result.stderr + result.stdout[-2000:])
                                    self.assertTrue((target / 'aikya/docs/indice.md').is_file())
                                    profile = json.loads((target / '.harness/project-profile.json').read_text())['decisions']
                                    self.assertEqual(kind, profile['project_type'])
                                    self.assertEqual(method, profile['methodology'])
                                    for outside in ('docs', 'plans', 'plan'):
                                        self.assertFalse((target / outside).exists(), outside)

    def previous_runtime(self, base):
        target, home = base / 'project', base / 'home'
        runtime = target / '.aikya/runtime'
        gallery = runtime / GALLERY
        gallery.mkdir(parents=True)
        previous = {}
        for name in ('managed.md', 'custom.md'):
            raw = b'# Historical example\n\nGENERATED BY AIKYA HARNESS\n'
            (gallery / name).write_bytes(raw)
            previous[GALLERY + '/' + name] = hashlib.sha256(raw).hexdigest()
        (gallery / 'custom.md').write_text('User-owned revision\n')
        (gallery / 'untracked.txt').write_text('Untracked user data\n')
        (runtime / 'manifest.json').write_text(json.dumps({'files': previous}))
        return target, home, runtime, previous

    def test_upgrade_backs_up_verified_bytes_and_preserves_custom_and_unknown_files(self):
        with tempfile.TemporaryDirectory() as temporary:
            target, home, runtime, previous = self.previous_runtime(Path(temporary))
            raw = (runtime / GALLERY / 'managed.md').read_bytes()
            aikya_setup.setup(ROOT, target, 'project', home=home)
            self.assertFalse((runtime / GALLERY / 'managed.md').exists())
            self.assertEqual(raw, (runtime / 'retired-assets' / GALLERY / 'managed.md').read_bytes())
            self.assertEqual('User-owned revision\n', (runtime / GALLERY / 'custom.md').read_text())
            self.assertEqual('Untracked user data\n', (runtime / GALLERY / 'untracked.txt').read_text())
            self.assertNotIn(GALLERY + '/managed.md', json.loads((runtime / 'manifest.json').read_text())['files'])
            aikya_setup.setup(ROOT, target, 'project', home=home)
            self.assertEqual('User-owned revision\n', (runtime / GALLERY / 'custom.md').read_text())

    def test_conflicting_backup_preserves_original(self):
        with tempfile.TemporaryDirectory() as temporary:
            target, home, runtime, previous = self.previous_runtime(Path(temporary))
            backup = runtime / 'retired-assets' / GALLERY / 'managed.md'
            backup.parent.mkdir(parents=True)
            backup.write_text('Existing different backup\n')
            with self.assertRaisesRegex(ValueError, 'backup'):
                aikya_setup.setup(ROOT, target, 'project', home=home)
            self.assertTrue((runtime / GALLERY / 'managed.md').is_file())
            self.assertEqual('Existing different backup\n', backup.read_text())

    def test_customized_guide_retains_its_local_gallery(self):
        with tempfile.TemporaryDirectory() as temporary:
            target, home, runtime, previous = self.previous_runtime(Path(temporary))
            guide = runtime / 'examples/documentation/README.md'
            guide.write_text('# Owner guide\n\n[Gallery](generated/README.es.md)\n')
            aikya_setup.setup(ROOT, target, 'project', home=home)
            self.assertTrue((runtime / GALLERY / 'managed.md').is_file())
            self.assertIn('# Owner guide', guide.read_text())

    def test_manifest_traversal_and_linked_gallery_directory_are_preserved(self):
        with tempfile.TemporaryDirectory() as temporary:
            base = Path(temporary)
            target, home, runtime, previous = self.previous_runtime(base)
            victim = runtime / 'examples/documentation/user.txt'
            victim.write_text('Owner content\n')
            previous[GALLERY + '/../user.txt'] = hashlib.sha256(victim.read_bytes()).hexdigest()
            (runtime / 'manifest.json').write_text(json.dumps({'files': previous}))
            aikya_setup.setup(ROOT, target, 'project', home=home)
            self.assertEqual('Owner content\n', victim.read_text())
            # A whole symlinked subtree must not be scanned or copied into backups.
            linked_target = base / 'linked'
            gallery = linked_target / '.aikya/runtime' / GALLERY
            gallery.parent.mkdir(parents=True)
            gallery.symlink_to(victim.parent, target_is_directory=True)
            linked_manifest = linked_target / '.aikya/runtime/manifest.json'
            linked_manifest.write_text(json.dumps({'files': {GALLERY + '/user.txt': hashlib.sha256(victim.read_bytes()).hexdigest()}}))
            aikya_setup.setup(ROOT, linked_target, 'project', home=home)
            self.assertTrue(gallery.is_symlink())
            self.assertEqual('Owner content\n', victim.read_text())

    def test_symlinked_gallery_and_backup_never_touch_external_data(self):
        for symlink in ('gallery', 'backup'):
            with self.subTest(symlink=symlink), tempfile.TemporaryDirectory() as temporary:
                base = Path(temporary)
                target, home, runtime, previous = self.previous_runtime(base)
                outside = base / 'outside'
                outside.mkdir()
                external = outside / 'managed.md'
                external.write_text('External content\n')
                if symlink == 'gallery':
                    link = runtime / GALLERY / 'managed.md'
                    link.unlink()
                    link.symlink_to(external)
                else:
                    (runtime / 'retired-assets').symlink_to(outside, target_is_directory=True)
                aikya_setup.setup(ROOT, target, 'project', home=home)
                self.assertEqual('External content\n', external.read_text())
                self.assertTrue((runtime / GALLERY / 'managed.md').exists())


if __name__ == '__main__':
    unittest.main()
