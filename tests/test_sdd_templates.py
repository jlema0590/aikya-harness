"""Aikya reference templates compositions must survive Aikya's real, approval-gated lifecycle."""
import importlib.util
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from aikya.workflows.sdd import engine as sdd
from aikya.installation import facade as install
from aikya.installation import registration as aikya_setup
from aikya.documentation.layout import validate_layout

FOOTER='GENERATED BY AIKYA HARNESS'

class SddTemplateTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup)
        self.root=Path(self.tmp.name)
        file=self.root/'.harness/project-profile.json';file.parent.mkdir()
        file.write_text(json.dumps({'_generated_by':'claude-dev-harness-interactive','schema_version':1,'decisions':{'project_type':'development','methodology':'sdd'}}))
        self.spec={'id':'SPEC-001','title':'Lookup contract fixture','objective':'Describe lookup behavior.',
                   'requirements':[{'id':'REQ-001','description':'Missing items return a stable error.','acceptance':['Given a missing item, lookup returns a documented not-found response.']}],
                   'questions':[],'nonfunctional':[]}
        self.folder=self.root/'aikya/docs/specs/development/SPEC-001'

    def ready(self,task_sections=None):
        sdd.initialize(self.root,self.spec)
        sdd.approve(self.root,'SPEC-001','spec','fixture reviewer')
        sdd.create_plan(self.root,'SPEC-001',{'design':'Reuse the existing lookup boundary.','testing':'Check the not-found response.','decisions':[],'risks':[]})
        sdd.approve(self.root,'SPEC-001','plan','fixture reviewer')
        task={'id':'TASK-001','description':'Implement the reviewed lookup response.','requirements':['REQ-001'],'depends_on':[]}
        if task_sections is not None:task['sections']=task_sections
        sdd.create_tasks(self.root,'SPEC-001',{'tasks':[task]})
        sdd.approve(self.root,'SPEC-001','tasks','fixture reviewer')

    def test_catalog_has_nine_attributed_offline_templates(self):
        self.assertIsNotNone(importlib.util.find_spec('sdd_templates'))
        from aikya.workflows.sdd import templates as sdd_templates
        self.assertEqual({'feature','api','database','spec','design','tasks','evidence','review','constitution'},set(sdd_templates.catalog()))
        for name,item in sdd_templates.catalog().items():
            with self.subTest(template=name):
                self.assertTrue(item['source'].startswith('aikya-template/docs/'))
                body=sdd_templates.starter(name)
                self.assertTrue(body.rstrip().endswith(FOOTER))
                self.assertIn(item['source'],body)

    def test_specialized_spec_sections_are_preserved_rendered_and_indexed(self):
        for name,key,value in [('feature','non_goals','No unrelated UI work.'),('api','endpoint','GET /items/{id}'),('database','migration','Expand schema before backfill.'),('spec','context','Observed lookup boundary.')]:
            with self.subTest(template=name):
                spec={**self.spec,'id':'SPEC-'+str(len(list((self.root/'aikya/docs/specs/development').glob('*'))) + 1).zfill(3),'template':name,'sections':{key:value}}
                result=sdd.initialize(self.root,spec);folder=self.root/result['path']
                state=json.loads((folder/'state.json').read_text())
                self.assertEqual(name,state['spec'].get('template'))
                self.assertEqual({key:value},state['spec'].get('sections'))
                self.assertIn(value,(folder/'spec.md').read_text())
                self.assertTrue((folder/'spec.md').read_text().rstrip().endswith(FOOTER))
                self.assertIn('specs/development/'+spec['id']+'/spec.md',(self.root/'aikya/docs/indice.md').read_text())
        self.assertEqual([],validate_layout(self.root))

    def test_unknown_or_empty_template_sections_are_rejected_before_writes(self):
        for extra in [{'template':'invented'}, {'template':'api','sections':{'invented':'Do something'}}, {'template':'api','sections':{'endpoint':''}}, {'template':'api','sections':{'endpoint':['Not a text field']}}]:
            with self.subTest(extra=extra):
                with self.assertRaises(ValueError):sdd.initialize(self.root,{**self.spec,**extra})
                self.assertFalse(self.folder.exists())

    def test_draft_omits_empty_clarification_and_verification_reports(self):
        sdd.initialize(self.root,self.spec)
        self.assertFalse((self.folder/'clarifications.md').exists())
        self.assertFalse((self.folder/'verification.md').exists())
        self.assertFalse((self.folder/'evidence.md').exists())
        self.assertTrue(sdd.validate(self.root)['valid'])

    def test_design_sections_survive_plan_and_differ_from_execution_plan(self):
        sdd.initialize(self.root,self.spec);sdd.approve(self.root,'SPEC-001','spec','fixture reviewer')
        sdd.create_plan(self.root,'SPEC-001',{'design':'Reuse lookup adapter.','testing':'Run lookup contract tests.','decisions':['Preserve errors.'],'risks':['Legacy clients.'],
                         'sections':{'alternatives':'A new service was rejected due to extra state.','rollback':'Restore the prior response adapter.'}})
        design=(self.folder/'design.md').read_text();plan=(self.folder/'plan.md').read_text()
        self.assertNotEqual(design,plan)
        self.assertIn('A new service was rejected',design)
        self.assertIn('Run lookup contract tests.',plan)
        self.assertEqual('Restore the prior response adapter.',json.loads((self.folder/'state.json').read_text())['plan']['sections']['rollback'])

    def test_tasks_keep_allowed_files_commands_and_completion_notes(self):
        self.ready({'owner':'Lookup team','allowed_files':'src/lookup.py and tests/test_lookup.py','checks':'python -m unittest tests.test_lookup','done_when':'REQ-001 has a checked response fixture.'})
        text=(self.folder/'tasks.md').read_text()
        self.assertIn('src/lookup.py and tests/test_lookup.py',text)
        self.assertIn('python -m unittest tests.test_lookup',text)
        task=sdd.require_approved_task(self.root,'SPEC-001','TASK-001')
        self.assertEqual('Lookup team',task.get('sections',{}).get('owner'))

    def test_evidence_template_is_created_from_actual_recorded_evidence_only(self):
        self.ready();self.assertFalse((self.folder/'evidence.md').exists())
        (self.root/'fixture-check.log').write_text('Controlled test fixture; no application command executed.\n')
        sdd.progress(self.root,'SPEC-001','TASK-001','done','fixture-check.log')
        sdd.verify(self.root,'SPEC-001',{'requirements':[{'id':'REQ-001','command':'fixture-check','result':'passed','evidence':'fixture-check.log'}],
                    'sections':{'known_gaps':'Production load testing was not performed.'}})
        self.assertTrue((self.folder/'evidence.md').is_file())
        text=(self.folder/'evidence.md').read_text()
        self.assertIn('fixture-check.log',text);self.assertIn('Production load testing was not performed.',text)
        self.assertTrue(text.rstrip().endswith(FOOTER))
        self.assertIs(False,json.loads((self.folder/'state.json').read_text())['verification']['independently_executed'])

    def test_review_and_constitution_require_approved_nonempty_content(self):
        function=getattr(sdd,'create_document',None);self.assertTrue(callable(function))
        sdd.initialize(self.root,self.spec)
        with self.assertRaises(ValueError):function(self.root,'review',{'sections':{'scope':'Observed files only.'}},ident='SPEC-001',approved=False)
        with self.assertRaises(ValueError):function(self.root,'constitution',{'sections':{}},approved=True)
        function(self.root,'review',{'sections':{'scope':'Observed files only.','decision':'Request changes until evidence is attached.'}},ident='SPEC-001',approved=True)
        function(self.root,'constitution',{'sections':{'principles':'Require approved requirements before implementation.'}},approved=True)
        self.assertTrue((self.folder/'review.md').is_file())
        self.assertTrue((self.root/'aikya/docs/specs/constitution.md').is_file())
        self.assertEqual({},json.loads((self.folder/'state.json').read_text())['approvals'])

    def test_persisted_unknown_sections_block_approval(self):
        sdd.initialize(self.root,self.spec)
        state=self.folder/'state.json';data=json.loads(state.read_text())
        data['spec'].update(template='api',sections={'run_arbitrary_action':'Never execute this.'})
        state.write_text(json.dumps(data))
        with self.assertRaises(ValueError):sdd.approve(self.root,'SPEC-001','spec','fixture reviewer')

    def test_custom_index_prevents_partial_specification_writes(self):
        index=self.root/'aikya/docs/indice.md';index.parent.mkdir(parents=True)
        index.write_text('# Team index\n\nOwner maintained.\n')
        with self.assertRaises(ValueError):sdd.initialize(self.root,self.spec)
        self.assertFalse(self.folder.exists())

    def test_installed_runtime_can_show_templates_without_source_imports_or_writes(self):
        profile=install.validated({**json.loads((ROOT/'examples/next-react/answers.json').read_text()),'methodology':'sdd'},self.root)
        install.install(self.root,profile,{'modules':[]})
        before={p.relative_to(self.root):p.read_bytes() for p in self.root.rglob('*') if p.is_file()}
        result=subprocess.run([sys.executable,'-B',str(self.root/'aikya/scripts/harness/sdd_engine.py'),'templates','--root',str(self.root),'--template','api'],cwd=self.root,capture_output=True,text=True)
        self.assertEqual(0,result.returncode,result.stderr)
        self.assertTrue(result.stdout.rstrip().endswith(FOOTER))
        self.assertIn('aikya-template/docs/general-swe/foundations/interface-control-document.md',result.stdout)
        self.assertEqual(before,{p.relative_to(self.root):p.read_bytes() for p in self.root.rglob('*') if p.is_file()})

    def test_spanish_headings_keep_user_sections_unchanged(self):
        policy=self.root/'.aikya/docs-policy.json';policy.parent.mkdir();policy.write_text(json.dumps({'schema_version':1,'language':'es'}))
        sdd.initialize(self.root,{**self.spec,'template':'feature','sections':{'non_goals':'No unrelated API changes.'}})
        text=(self.folder/'spec.md').read_text()
        self.assertIn('## Fuera de alcance',text);self.assertIn('No unrelated API changes.',text)
        self.assertTrue(text.rstrip().endswith(FOOTER))



    def test_approval_does_not_fabricate_a_task_progress_event(self):
        sdd.initialize(self.root,self.spec)
        legacy='<!-- GENERATED BY AIKYA SDD 6.1.1 -->\n# Verification\n\nNo result was recorded.\n'
        report=self.folder/'verification.md';report.write_text(legacy)
        sdd.approve(self.root,'SPEC-001','spec','fixture reviewer')
        self.assertEqual(legacy,report.read_text())

    def test_unindexable_document_blocks_approval_without_saving_state(self):
        sdd.initialize(self.root,self.spec)
        state=self.folder/'state.json';before=state.read_bytes()
        (self.root/'aikya/docs/unrelated.md').symlink_to(self.root/'missing.md')
        with self.assertRaises(ValueError):sdd.approve(self.root,'SPEC-001','spec','fixture reviewer')
        self.assertEqual(before,state.read_bytes())

    def test_unindexable_document_blocks_new_spec_and_review_without_writes(self):
        sdd.initialize(self.root,self.spec)
        (self.root/'aikya/docs/unrelated.md').symlink_to(self.root/'missing.md')
        with self.assertRaises(ValueError):sdd.initialize(self.root,{**self.spec,'id':'SPEC-002'})
        self.assertFalse(self.folder.with_name('SPEC-002').exists())
        with self.assertRaises(ValueError):sdd.create_document(self.root,'review',{'sections':{'decision':'Needs revision.'}},ident='SPEC-001',approved=True)
        self.assertFalse((self.folder/'review.md').exists())

    def test_spanish_verification_invalidation_is_localized(self):
        policy=self.root/'.aikya/docs-policy.json';policy.parent.mkdir();policy.write_text(json.dumps({'schema_version':1,'language':'es'}))
        self.ready()
        (self.root/'fixture.log').write_text('Fixture evidence only.')
        sdd.progress(self.root,'SPEC-001','TASK-001','done','fixture.log')
        sdd.verify(self.root,'SPEC-001',{'requirements':[{'id':'REQ-001','command':'fixture','result':'passed','evidence':'fixture.log'}]})
        sdd.progress(self.root,'SPEC-001','TASK-001','in_progress',None)
        for name in ('verification.md','evidence.md'):
            body=(self.folder/name).read_text()
            self.assertIn('# Verificación invalidada',body)
            self.assertIn('El progreso de las tareas cambió',body)
            self.assertTrue(body.rstrip().endswith(FOOTER))

if __name__=='__main__':unittest.main()
