/* Real user interactions against synthetic HTML only; no private project fixture. */
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require('playwright');
(async()=>{
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1560,height:1050}});
  const errors=[],external=[],checks=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  page.on('request',r=>{if(/^https?:/.test(r.url()))external.push(r.url());});
  const check=(name,value)=>{assert.ok(value,name);checks.push(name);};
  const wait=()=>page.waitForTimeout(260);
  const position=locator=>locator.evaluate(el=>{const m=new DOMMatrix(getComputedStyle(el).transform);return [m.m41,m.m42];});
  const camera=()=>page.locator('#canvas').getAttribute('style');
  try {
    await page.goto(pathToFileURL(path.resolve(process.argv[2])).href);
    await page.waitForFunction(()=>document.querySelector('.label[visibility="visible"]'));
    check('Overview exposes expandable folders',await page.locator('.node .expand').count()>0);
    check('Expansion controls have a 24px interaction target',(await page.locator('.expand circle').first().boundingBox()).width>=23.9);
    check('Overview groups file declarations instead of piling them up',await page.locator('.node').count()<30);
    check('Visible labels do not cover their own component',await page.evaluate(()=>[...document.querySelectorAll('.node')].every(group=>{
      const label=group.querySelector('.label');if(getComputedStyle(label).visibility==='hidden')return true;
      const a=label.getBoundingClientRect(),b=group.querySelector('circle.body').getBoundingClientRect();
      return !(a.left<b.right&&a.right>b.left&&a.top<b.bottom&&a.bottom>b.top);
    })));
    check('Visible labels do not overlap one another',await page.evaluate(()=>{
      const boxes=[...document.querySelectorAll('.label')].filter(el=>getComputedStyle(el).visibility==='visible').map(el=>el.getBoundingClientRect());
      return boxes.every((a,i)=>boxes.slice(i+1).every(b=>!(a.left<b.right&&a.right>b.left&&a.top<b.bottom&&a.bottom>b.top)));
    }));
    const folder=page.locator('.node[data-node-id="folder:0"]');
    await folder.locator('.expand').click();await wait();
    check('Expanding a folder reveals files',await page.locator('.node.file:not(.exiting)').count()===9);
    await page.locator('#zoom-reset').click();await wait();
    const node=page.locator('.node[data-node-id="file:0"]');
    await node.focus();await node.press('Enter');
    check('Inspector preserves the actual direction of incoming containment',await page.locator('#connections button').first().textContent()==='module-0 — contains → Source-0.java');
    const handle=await node.elementHandle();
    await node.press('Enter');
    check('Selection retains the same DOM node and focus',await page.evaluate(el=>el.isConnected&&el===document.activeElement,handle));
    const before=await position(node),bounds=await node.locator('circle.body').boundingBox();
    await page.mouse.move(bounds.x+bounds.width/2,bounds.y+bounds.height/2);
    await page.mouse.down();await page.mouse.move(bounds.x+bounds.width/2+65,bounds.y+bounds.height/2+35,{steps:6});await page.mouse.up();
    const moved=await position(node);
    check('Node drag updates its position',Math.hypot(moved[0]-before[0],moved[1]-before[1])>30);
    check('Node drag pins only a visual position',await node.getAttribute('data-pinned')==='true');
    check('Incident links follow the moved node',await page.evaluate(()=>{
      const n=document.querySelector('[data-node-id="file:0"]'),p=new DOMMatrix(getComputedStyle(n).transform);
      const links=[...document.querySelectorAll('.connection')].filter(e=>e.dataset.target==='file:0');
      return links.length>0&&links.every(e=>Math.abs(Number(e.querySelector('.edge').getAttribute('x2'))-p.m41)<.01&&Math.abs(Number(e.querySelector('.edge').getAttribute('y2'))-p.m42)<.01);
    }));
    await node.locator('.expand').click();await wait();
    check('A new expansion click immediately after dragging is not swallowed',await page.locator('.node.class:not(.exiting),.node.method:not(.exiting)').count()===2);
    await page.locator('#type').selectOption('class');await wait();
    check('Type filtering reaches grouped declarations',await page.locator('.node:not(.exiting)').count()===88&&await page.locator('.node.class').count()===88);
    await page.locator('#type').selectOption('all');await page.locator('#folder').selectOption('module-0');await wait();
    check('Folder filtering exposes only that verified subtree',await page.locator('.node:not(.exiting)').count()===28);
    await page.locator('#folder').selectOption('all');await page.locator('#neighbors').click();await wait();
    check('Neighbors only shows the selected source and its three neighbors',await page.locator('.node:not(.exiting)').count()===4);
    await page.locator('#neighbors').click();await wait();
    await node.locator('.expand').click();await wait();
    await node.focus();await node.press('ArrowRight');
    check('Keyboard can move the focused object', (await position(node))[0]>moved[0]);
    await page.locator('[data-view=architecture]').click();await wait();
    await page.locator('[data-view=graph]').click();await wait();
    check('Manual positions survive switching views', (await position(node))[0]>moved[0]);
    const retained=await position(node);
    await page.locator('#search').fill('Source-0.java');await wait();
    await page.locator('#search').fill('');await wait();
    check('Manual positions survive filtering',Math.abs((await position(node))[0]-retained[0])<.01);
    const camBefore=await camera();
    await page.locator('#zoom-in').click();await wait();
    check('Zoom changes the camera without resetting node positions',await camera()!==camBefore&&Math.abs((await position(node))[0]-retained[0])<.01);
    for(let step=0;step<8;step++)await page.locator('#zoom-in').click();await wait();
    check('Labels remain clear of their component at high zoom',await page.evaluate(()=>[...document.querySelectorAll('.node')].every(group=>{
      const label=group.querySelector('.label');if(getComputedStyle(label).visibility==='hidden')return true;
      const a=label.getBoundingClientRect(),b=group.querySelector('circle.body').getBoundingClientRect();
      return !(a.left<b.right&&a.right>b.left&&a.top<b.bottom&&a.bottom>b.top);
    })));
    await page.locator('#zoom-reset').click();await wait();
    const cancelBefore=await position(node),cancelBox=await node.locator('circle.body').boundingBox();
    await page.mouse.move(cancelBox.x+cancelBox.width/2,cancelBox.y+cancelBox.width/2);await page.mouse.down();
    await page.mouse.move(cancelBox.x+cancelBox.width/2+45,cancelBox.y+cancelBox.width/2+25,{steps:4});
    await page.keyboard.press('Escape');await page.mouse.up();
    check('Escape restores the starting position',Math.hypot(...(await position(node)).map((v,i)=>v-cancelBefore[i]))<.01);
    const panBefore=await camera(),stage=await page.locator('#graph').boundingBox();
    await page.mouse.move(stage.x+stage.width-8,stage.y+stage.height-8);await page.mouse.down();
    await page.mouse.move(stage.x+stage.width-48,stage.y+stage.height-38,{steps:4});await page.mouse.up();
    check('Dragging the background pans without moving objects',await camera()!==panBefore&&Math.abs((await position(node))[0]-cancelBefore[0])<.01);
    const cancelPointerPosition=await position(node),cancelPointerBox=await node.locator('circle.body').boundingBox();
    await page.mouse.move(cancelPointerBox.x+cancelPointerBox.width/2,cancelPointerBox.y+cancelPointerBox.height/2);await page.mouse.down();
    await page.mouse.move(cancelPointerBox.x+cancelPointerBox.width/2+25,cancelPointerBox.y+cancelPointerBox.height/2+30,{steps:3});
    await node.dispatchEvent('pointercancel',{pointerId:1});await page.mouse.up();
    check('Pointer cancellation restores position and releases dragging state',Math.hypot(...(await position(node)).map((v,i)=>v-cancelPointerPosition[i]))<.01&&!await page.locator('#graph').evaluate(el=>el.classList.contains('dragging')));
    const switchingPosition=await position(node),switchingBox=await node.locator('circle.body').boundingBox();
    await page.mouse.move(switchingBox.x+switchingBox.width/2,switchingBox.y+switchingBox.height/2);await page.mouse.down();
    await page.mouse.move(switchingBox.x+switchingBox.width/2+30,switchingBox.y+switchingBox.height/2+20,{steps:3});
    await page.locator('[data-view=architecture]').focus();await page.locator('[data-view=architecture]').press('Enter');await page.mouse.up();await wait();
    await page.locator('[data-view=graph]').click();await wait();
    check('Switching views cancels an in-progress drag in its original view',Math.hypot(...(await position(node)).map((v,i)=>v-switchingPosition[i]))<.01);
    await page.locator('#zoom-reset').click();await wait();
    await page.locator('[data-view=architecture]').click();await wait();
    const architectureFolder=page.locator('[data-node-id="folder:0"]');await architectureFolder.focus();await architectureFolder.press('ArrowRight');
    const architecturePosition=await position(architectureFolder);
    await page.locator('[data-view=graph]').click();await wait();
    await page.locator('#layout-reset').click();await wait();
    check('Reset layout releases manual positions',await node.getAttribute('data-pinned')!=='true');
    await page.locator('[data-view=architecture]').click();await wait();
    check('Reset layout does not clear another view',Math.abs((await position(architectureFolder))[0]-architecturePosition[0])<.01&&await architectureFolder.getAttribute('data-pinned')==='true');
    await page.locator('[data-view=graph]').click();await wait();
    await page.locator('.node[data-node-id="project:root"]').focus();
    await page.locator('.node[data-node-id="project:root"]').press('Enter');
    check('Verified directed connections have flow animation',await page.locator('.edge-flow.directed.flowing').count()>0);
    check('Animation keeps a readable base line',await page.locator('.connection .edge').count()>0);
    await page.locator('.node[data-node-id="folder:0"]').focus();
    await page.locator('.node[data-node-id="folder:0"]').press('Enter');
    check('Undirected evidence uses a pulse without arrow travel',await page.locator('.edge-flow.undirected.flowing').count()===1);
    await page.locator('#motion').click();
    check('Motion off stops connection effects',await page.locator('.edge-flow.flowing').count()===0);
    await page.locator('#motion').click();await page.emulateMedia({reducedMotion:'reduce'});
    await wait();
    check('Reduced motion stops connection effects',await page.locator('.edge-flow.flowing').count()===0);
    await page.locator('[data-view=inventory]').click();
    check('Inventory is exclusive',!await page.locator('#graph').isVisible());
    await page.locator('#theme').click();
    check('Light theme preserves exclusive Inventory',!await page.locator('#graph').isVisible());
    for(let step=0;step<8;step++){await page.keyboard.press('Tab');check('Hidden SVG is absent from tab navigation '+step,await page.evaluate(()=>!document.querySelector('#graph').contains(document.activeElement)));}
    for(const [pageNumber,count] of [[1,100],[2,100],[3,75]]) {
      check('Inventory page '+pageNumber,await page.locator('.inventory-row').count()===count);
      if(pageNumber<3)await page.locator('#next').click();
    }
    await page.locator('#previous').click();check('Previous page remains navigable',await page.locator('.inventory-row').count()===100);await page.locator('#next').click();
    await page.locator('.inventory-row').first().click();
    check('Inventory rows receive clicks',Boolean(await page.locator('#detail-path').textContent()));
    check('No JS/CSP errors',errors.length===0);check('No external requests',external.length===0);
    if(process.env.AIKYA_BROWSER_SCREENSHOT){await page.locator('[data-view=graph]').click();await page.screenshot({path:process.env.AIKYA_BROWSER_SCREENSHOT});}
    console.log(JSON.stringify({checks,errors,external},null,2));
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
