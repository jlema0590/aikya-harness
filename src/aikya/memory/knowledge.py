"""Reviewed, scoped reference memories; never task evidence or approvals."""
from __future__ import annotations
import argparse,json,math,re,time
from pathlib import Path
from aikya.core.checkpoints import safe_file,fingerprint,sha,identity
from aikya.core.state import locked
from aikya.documentation.layout import content,write_document,stamp
import aikya.memory.store as stores

KINDS=('user','feedback','project','reference')
BASE_KEYS={'schema','id','kind','source','source_hash','created_at','ttl_days'}
REVIEW_KEYS={'scope','project_identity','review_state','reviewed_at','origin','extraction_id'}


def moment(now=None):
    value=time.time() if now is None else now
    if type(value) not in (int,float) or not math.isfinite(value) or value<0:raise ValueError('Invalid memory time')
    return value


def validate_input(root,raw):
    required={'kind','text','source','ttl_days'}
    if not isinstance(raw,dict) or not required<=set(raw) or set(raw)-required-{'scope'}:raise ValueError('Invalid memory schema')
    if raw['kind'] not in KINDS or not isinstance(raw['text'],str) or not raw['text'].strip() or len(raw['text'])>8000 or '\x00' in raw['text']:raise ValueError('Invalid memory content/type')
    if type(raw['ttl_days']) is not int or not 1<=raw['ttl_days']<=365:raise ValueError('Memory TTL must be 1–365 days')
    if raw.get('scope','project') not in stores.SCOPES:raise ValueError('Invalid memory scope')
    source=safe_file(root,raw['source'])
    if not source.is_file():raise ValueError('Current project source is required')
    return {**raw,'text':raw['text'].strip(),'scope':raw.get('scope','project')},fingerprint(source)


def _note(root,path):
    try:
        if path.is_symlink() or path.stat().st_size>20000:return None
        text=path.read_text(encoding='utf8')
        if not text.endswith('GENERATED BY AIKYA HARNESS\n'):return None
        head,meta,body=text.split('---',2)
        if head.strip():return None
        obj=json.loads(meta)
        if not isinstance(obj,dict) or type(obj.get('schema')) is not int:return None
        if set(obj)!=(BASE_KEYS if obj['schema']==1 else BASE_KEYS|REVIEW_KEYS) or obj['schema'] not in (1,2) or obj['kind'] not in KINDS:return None
        moment(obj['created_at'])
        if type(obj['ttl_days']) is not int or not 1<=obj['ttl_days']<=365:return None
        body=content(body)
        if not body or len(body)>8000 or '\x00' in body:return None
        ident=sha({'kind':obj['kind'],'text':' '.join(body.split()),'source':obj['source']})[:24]
        if ident!=obj['id'] or path.stem!=ident:return None
        safe_file(root,obj['source'])
        if not isinstance(obj['source_hash'],str) or not re.fullmatch('[a-f0-9]{64}',obj['source_hash']):return None
        if obj['schema']==2:
            if obj['scope'] not in stores.SCOPES or obj['review_state'] not in ('pending','approved','rejected') or obj['origin'] not in ('manual','model'):return None
            if not re.fullmatch('[a-f0-9]{64}',obj['project_identity']):return None
            if obj['review_state']=='pending':
                if obj['reviewed_at'] is not None:return None
            else:moment(obj['reviewed_at'])
            if obj['extraction_id'] is not None and not re.fullmatch('[a-f0-9]{32}',obj['extraction_id']):return None
        else:
            # Old notes had no checkout binding. Preserve them, but bind only
            # through a new explicit review; a copied note cannot prove identity.
            obj.update(scope='project',project_identity=None,review_state='approved',reviewed_at=obj['created_at'],origin='manual',extraction_id=None)
        return {**obj,'text':body}
    except (ValueError,OSError,TypeError,KeyError):return None


def _body(note):
    return '---\n'+json.dumps({k:v for k,v in note.items() if k!='text'},ensure_ascii=False)+'\n---\n\n'+note['text']


def _check_index(root,scope,private_root=None):
    target=stores.store_root(root,scope,private_root)/'MEMORY.md'
    if target.is_symlink() or (target.exists() and not target.read_text().rstrip().endswith('GENERATED BY AIKYA HARNESS')):raise ValueError('Custom memory index is protected')


def _index(root,scope,private_root=None):
    base=stores.store_root(root,scope,private_root);target=base/'MEMORY.md';lines=[]
    _check_index(root,scope,private_root)
    for path in sorted(base.glob('*.md'))[:101]:
        if path.name=='MEMORY.md':continue
        note=_note(root,path)
        if note:lines.append('- ['+note['id']+']('+path.name+') — '+note['kind']+' / '+note['review_state'])
    stores.write(root,target,'# '+scope.title()+' reference memories\n\n'+'\n'.join(lines),scope)


def _guard(root,scope,private_root=None):
    guard=stores.store_root(root,scope,private_root,create=True) if scope=='private' else safe_file(root,'.harness/state/memory/guard').parent
    guard.mkdir(parents=True,exist_ok=True)
    return guard


def _create(root,raw,state,*,private_root=None,now=None,origin='manual',extraction_id=None):
    root=Path(root).absolute();when=moment(now);raw,source_hash=validate_input(root,raw)
    if origin not in ('manual','model') or (origin=='model' and state!='pending'):raise ValueError('Model notes require explicit later review')
    if extraction_id is not None and (not isinstance(extraction_id,str) or not re.fullmatch('[a-f0-9]{32}',extraction_id)):raise ValueError('Invalid extraction ID')
    ident=sha({k:(' '.join(raw[k].split()) if k=='text' else raw[k]) for k in ('kind','text','source')})[:24]
    scope=raw['scope'];base=stores.store_root(root,scope,private_root,create=True)
    path=stores.note_path(root,ident,scope,private_root)
    with locked(_guard(root,scope,private_root)):
        _check_index(root,scope,private_root)
        if path.exists():
            note=_note(root,path)
            if not note or note['source_hash']!=source_hash or note['project_identity']!=identity(root) or note['scope']!=scope:raise ValueError('Custom, moved or stale memory requires review')
            # Duplicate proposals can never promote a pending/rejected note.
            return stores.reference(root,path,scope)
        note={'schema':2,'id':ident,'kind':raw['kind'],'source':raw['source'],'source_hash':source_hash,'created_at':when,'ttl_days':raw['ttl_days'],
              'scope':scope,'project_identity':identity(root),'review_state':state,'reviewed_at':when if state=='approved' else None,'origin':origin,'extraction_id':extraction_id,'text':raw['text']}
        stores.write(root,path,_body(note),scope);_index(root,scope,private_root)
        return stores.reference(root,path,scope)


def remember(root,raw,*,approved=False,now=None,private_root=None):
    if approved is not True:raise ValueError('Reviewed memory content requires explicit authorization')
    return _create(root,raw,'approved',now=now,private_root=private_root)


def propose(root,raw,*,now=None,private_root=None,origin='manual',extraction_id=None):
    return _create(root,raw,'pending',now=now,private_root=private_root,origin=origin,extraction_id=extraction_id)


def review(root,ident,*,decision,scope='project',approved=False,now=None,private_root=None):
    if approved is not True or decision not in ('approved','rejected'):raise ValueError('Explicit memory review decision is required')
    root=Path(root).absolute();when=moment(now);path=stores.note_path(root,ident,scope,private_root)
    with locked(_guard(root,scope,private_root)):
        note=_note(root,path)
        if not note or (note['schema']==2 and note['project_identity']!=identity(root)) or note['scope']!=scope:raise ValueError('Invalid, custom or moved memory')
        if fingerprint(safe_file(root,note['source']))!=note['source_hash']:raise ValueError('Review source changed; create a new current proposal')
        if when<note['created_at'] or when>=note['created_at']+note['ttl_days']*86400:raise ValueError('Review requires a current unexpired memory')
        _check_index(root,scope,private_root)
        note.update(schema=2,project_identity=identity(root),review_state=decision,reviewed_at=when)
        stores.write(root,path,_body(note),scope);_index(root,scope,private_root)
        return stores.reference(root,path,scope)


def migrate(root,previous_identity,*,scope='project',approved=False,private_root=None):
    if approved is not True:raise ValueError('Explicit memory migration approval is required')
    if not isinstance(previous_identity,str) or not re.fullmatch('[a-f0-9]{64}',previous_identity):raise ValueError('Invalid previous identity')
    root=Path(root).absolute();current=identity(root)
    if current==previous_identity:raise ValueError('Source and destination identities are equal')
    source=stores.store_root(root,scope,private_root,identity_key=previous_identity)
    target=stores.store_root(root,scope,private_root,create=True);changes=[]
    # Preflight every note before changes; old private stores remain intact.
    with locked(_guard(root,scope,private_root)):
        for path in sorted(source.glob('*.md')):
            if path.name=='MEMORY.md':continue
            note=_note(root,path)
            if not note or note['schema']!=2 or note['project_identity'] not in (previous_identity,current) or note['scope']!=scope:raise ValueError('Migration requires intact notes with the prior identity')
            if fingerprint(safe_file(root,note['source']))!=note['source_hash']:raise ValueError('Migration source changed')
            dest=target/path.name
            note['project_identity']=current
            if scope=='private' and dest.exists():
                existing=_note(root,dest)
                if not existing or _body(existing)!=_body(note):raise ValueError('Destination conflict; preserve both private stores')
            changes.append((dest,note))
        if not changes:raise ValueError('No matching memories to migrate')
        _check_index(root,scope,private_root)
        migration_id=sha({'from':previous_identity,'to':current,'notes':[n['id'] for _,n in changes]})[:24]
        def receipt(status):
            body='# Memory identity migration\n\n'+ '\n'.join('- '+k+': '+str(v) for k,v in {'from_identity':previous_identity,'to_identity':current,'scope':scope,'status':status,'approved_at':moment(),'notes':[n['id'] for _,n in changes]}.items())
            if scope=='project':write_document(root,'memory-migrations/'+migration_id+'.md',body,replace_generated=True)
            else:
                from aikya.storage import atomic_write
                path=stores.private_subdir(root,'migrations',private_root)/(migration_id+'.md')
                if path.exists() and not path.read_text().rstrip().endswith('GENERATED BY AIKYA HARNESS'):raise ValueError('Customized migration receipt')
                atomic_write(path,stamp(body),mode=0o600)
        receipt('in_progress')
        for dest,note in changes:stores.write(root,dest,_body(note),scope)
        _index(root,scope,private_root)
        receipt('completed')
    return [stores.reference(root,p,scope) for p,_ in changes]


def note_status(root,note,when,*,source_hashes=None):
    """One eligibility rule for recall and read-only inspection; never changes notes."""
    cache=source_hashes if source_hashes is not None else {}
    source=note['source']
    if source not in cache:
        try:cache[source]=fingerprint(safe_file(root,source))
        except (ValueError,OSError):cache[source]='unavailable'
    current=cache[source]
    source_status=('missing' if current is None else 'unavailable' if current=='unavailable'
                   else 'current' if current==note['source_hash'] else 'changed')
    expired=when>=note['created_at']+note['ttl_days']*86400
    same_identity=note['project_identity']==identity(root)
    eligible=(same_identity and note['review_state']=='approved' and
              when>=note['created_at'] and not expired and source_status=='current')
    return {'source_status':source_status,'expired':expired,'identity_matches':same_identity,
            'eligible_for_recall':eligible}


def inspect_notes(root,*,now=None,limit=5000,max_input_bytes=104857600):
    """Inspect only project notes, including non-recallable records; no writes."""
    from aikya.memory.contracts import NoteInspection
    if type(limit) is not int or not 1<=limit<=5000:raise ValueError('Invalid note inventory limit')
    if type(max_input_bytes) is not int or not 1<=max_input_bytes<=104857600:raise ValueError('Invalid note input budget')
    root=Path(root).absolute();when=moment(now);result=NoteInspection();hashes={}
    base=safe_file(root,'aikya/docs/memory/MEMORY.md').parent
    if not base.is_dir():return result
    from itertools import islice
    paths=list(islice(base.glob('*.md'),limit+2))
    paths=sorted(p for p in paths if p.name!='MEMORY.md')
    if len(paths)>limit:result.omitted_count+=len(paths)-limit;result.diagnostics.append('note_limit')
    remaining=max_input_bytes
    for position,path in enumerate(paths[:limit]):
        try:size=path.stat().st_size
        except OSError:result.omitted_count+=1;continue
        if path.is_symlink() or size>20000:result.omitted_count+=1;continue
        if size>remaining:
            result.omitted_count+=len(paths[:limit])-position;result.diagnostics.append('note_input_limit');break
        remaining-=size
        note=_note(root,path)
        if not note or note['scope']!='project':
            result.omitted_count+=1;continue
        if note['source'] not in hashes:
            try:
                from aikya.code_index.policy import read_source,content_hash
                source=safe_file(root,note['source']);source_size=source.stat().st_size
                if source_size>min(remaining,10000000):raise ValueError('Note source exceeds remaining input budget')
                remaining-=source_size
                hashes[note['source']]=content_hash(read_source(root,note['source'],source_size))
            except FileNotFoundError:hashes[note['source']]=None
            except (OSError,ValueError):
                hashes[note['source']]='unavailable'
                if 'note_source_unavailable' not in result.diagnostics:result.diagnostics.append('note_source_unavailable')
        result.notes.append({**note,**note_status(root,note,when,source_hashes=hashes),
                             'path':path.relative_to(root).as_posix()})
    return result


def recall(root,query,budget_chars,*,now=None,scopes=('project',),private_root=None):
    if type(budget_chars) is not int or not 0<=budget_chars<=16000:raise ValueError('Invalid total memory budget')
    if not isinstance(query,str) or len(query)>10000:raise ValueError('Invalid memory query')
    if not isinstance(scopes,(list,tuple)) or not scopes or any(s not in stores.SCOPES for s in scopes) or len(set(scopes))!=len(scopes):raise ValueError('Invalid memory scopes')
    if budget_chars==0:return ''
    root=Path(root).absolute();when=moment(now);words=set(re.findall(r'\w+',query.lower()));candidates=[]
    for scope in scopes:
        for path in sorted(stores.store_root(root,scope,private_root).glob('*.md'))[:101]:
            if path.name=='MEMORY.md':continue
            note=_note(root,path)
            if not note or note['scope']!=scope or not note_status(root,note,when)['eligible_for_recall']:continue
            score=len(words&set(re.findall(r'\w+',note['text'].lower())))
            if score:candidates.append((-score,note['id'],scope,note['text']))
    chunks=[];remaining=budget_chars;seen=set()
    for _,ident,scope,text in sorted(candidates):
        if ident in seen:continue
        seen.add(ident);chunk=('\n' if chunks else '')+'[reference '+ident+'] '+text
        chunks.append(chunk[:remaining]);remaining-=len(chunks[-1])
        if not remaining or len(chunks)==5:break
    return ''.join(chunks)


def main(argv=None):
    p=argparse.ArgumentParser(description='Reviewed project/private reference memories')
    p.add_argument('action',choices=('add','propose','review','recall','migrate'));p.add_argument('--root',type=Path,default=Path.cwd());p.add_argument('--input',type=Path)
    p.add_argument('--query',default='');p.add_argument('--budget-chars',type=int,default=4000);p.add_argument('--approved',action='store_true');p.add_argument('--scope',choices=stores.SCOPES,default='project')
    p.add_argument('--include-private',action='store_true');p.add_argument('--private-root',type=Path);p.add_argument('--id');p.add_argument('--decision',choices=('approved','rejected'));p.add_argument('--from-identity');a=p.parse_args(argv)
    try:
        options={'private_root':a.private_root}
        if a.action=='recall':result=recall(a.root,a.query,a.budget_chars,scopes=['project','private'] if a.include_private else [a.scope],**options)
        elif a.action=='review':result=review(a.root,a.id,decision=a.decision,scope=a.scope,approved=a.approved,**options)
        elif a.action=='migrate':result=migrate(a.root,a.from_identity,scope=a.scope,approved=a.approved,**options)
        else:
            if not a.input or a.input.is_symlink() or not a.input.is_file() or a.input.stat().st_size>20000:raise ValueError('Reviewed regular JSON input required')
            raw=json.loads(a.input.read_text())
            if not isinstance(raw,dict):raise ValueError('Memory object required')
            if 'scope' not in raw:raw['scope']=a.scope
            result=remember(a.root,raw,approved=a.approved,**options) if a.action=='add' else propose(a.root,raw,**options)
        print(json.dumps({'result':result},ensure_ascii=False));return 0
    except (ValueError,OSError,TypeError,KeyError) as exc:print('ERROR: '+str(exc));return 2
if __name__=='__main__':raise SystemExit(main())
