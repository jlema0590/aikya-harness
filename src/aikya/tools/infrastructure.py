#!/usr/bin/env python3
"""Generador Infrastructure & DevOps de Aikya.

'plan' es sólo lectura. 'generate --approved' crea archivos locales
sin sobrescribir ningún archivo existente. 'validate' ejecuta exclusivamente
validadores locales no destructivos, sin contactos con clusters ni clouds.
No se descargan herramientas ni se gestionan credenciales.
"""
from __future__ import annotations
from aikya.resource_paths import project_root
import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path
# The source template resolves the shared helper from its distribution root.
from aikya.documentation.layout import stamp

ROOT = project_root()
ENV_PATTERN = re.compile(r'^[a-z][a-z0-9-]{0,30}$')
MARK = '# GENERATED BY AIKYA-HARNESS — Infrastructure proposal, review before deployment\n'


def read_profile(root: Path) -> dict:
    file = root/'.harness/project-profile.json'
    raw = json.loads(file.read_text(encoding='utf8'))
    if not isinstance(raw, dict) or not isinstance(raw.get('decisions'), dict):
        raise ValueError('Perfil Aikya no encontrado o inválido; ejecuta /aikya-init')
    return raw['decisions']


def infrastructure(profile: dict) -> dict:
    # La instalación normal ya valida; lectura defensiva del perfil persistido.
    info = profile.get('infrastructure', {})
    if not isinstance(info, dict):
        raise ValueError('infrastructure debe ser un objeto JSON')
    c = info.get('containers', {})
    if not isinstance(c, dict):
        raise ValueError('containers debe ser un objeto JSON')
    return {
        'provider': info.get('provider', 'none'),
        'iac': info.get('iac', 'none'),
        'configuration_management': info.get('configuration_management', 'none'),
        'containers': {'enabled': c.get('enabled',False), 'compose': c.get('compose',False)},
        'orchestration': info.get('orchestration','none'),
        'deployment_method': info.get('deployment_method','none'),
        'environments': info.get('environments',[]),
        'image_repository': info.get('image_repository',''),
        'container_port': info.get('container_port'),
        'source_kind': info.get('source_kind','none'),
        'helm_chart_mode': info.get('helm_chart_mode','create'),
        'helm_chart_path': info.get('helm_chart_path',''),
    }


def applications(root: Path, profile: dict) -> list[tuple[str, Path]]:
    """No adivinar módulos existentes ni generar aplicaciones."""
    if profile.get('repository_layout','monorepo') == 'singlerepo':
        return [('app', root)]
    options=[('api',root/'apps/api'),('web',root/'apps/web'),
             ('frontend',root/'apps/frontend'),('mobile',root/'apps/mobile')]
    return [(name,folder) for name,folder in options if folder.is_dir()]


def node_major(root: Path, profile: dict) -> str | None:
    nvm=root/'.nvmrc'
    text=nvm.read_text(encoding='utf8').strip() if nvm.is_file() else str(profile.get('runtime_versions',''))
    match=re.search(r'(?<![\d.])(?:node(?:\.js)?\s*)?v?(\d{2})(?:\.\d+)*', text, re.IGNORECASE)
    return match.group(1) if match else None


def dockerfiles(root: Path, profile: dict) -> tuple[dict[str,str],list[str]]:
    artifacts={}
    pending=[]
    for name, folder in applications(root,profile):
        if not folder.is_dir():
            continue
        # La aplicación debe existir realmente antes de inferir comandos de build.
        pkg=folder/'package.json'
        pom=folder/'pom.xml'
        if pkg.is_file():
            raw=json.loads(pkg.read_text(encoding='utf8'))
            scripts=raw.get('scripts',{}) if isinstance(raw,dict) else {}
            scripts=scripts if isinstance(scripts,dict) else {}
            npm_lock=folder/'package-lock.json'
            major=node_major(folder,profile)
            if not npm_lock.is_file() or not major:
                pending.append(f'{name}: fijar versión Node (runtime_versions/.nvmrc) y package-lock.json antes del Dockerfile')
                continue
            if 'start' not in scripts:
                pending.append(f'{name}: package.json necesita script start confirmado')
                continue
            run_build='RUN npm run build\n' if 'build' in scripts else ''
            dockerfile=(MARK+
                f'ARG NODE_VERSION={major}\n'
                'FROM node:${NODE_VERSION}-bookworm-slim AS build\n'
                'WORKDIR /srv/app\n'
                'COPY package*.json ./\n'
                'RUN npm ci\n'
                'COPY . .\n'+run_build+
                'RUN npm prune --omit=dev\n'
                'FROM node:${NODE_VERSION}-bookworm-slim\n'
                'ENV NODE_ENV=production\n'
                'WORKDIR /srv/app\n'
                'COPY --from=build --chown=node:node /srv/app ./\n'
                'USER node\n'
                'CMD ["npm","run","start"]\n')
        elif pom.is_file() and (folder/'mvnw').is_file():
            version=re.search(r'\b(?:java|jdk)\s*(\d{2})\b',str(profile.get('runtime_versions','')),re.I)
            if not version:
                pending.append(f'{name}: fijar versión de Java/JDK antes del Dockerfile')
                continue
            dockerfile=(MARK+
                f'FROM eclipse-temurin:{version.group(1)}-jdk AS build\n'
                'WORKDIR /build\nCOPY . .\n'
                'RUN chmod +x ./mvnw && ./mvnw -B -DskipTests package\n'
                'FROM eclipse-temurin:'+version.group(1)+'-jre\n'
                'WORKDIR /app\nRUN groupadd -r app && useradd -r -g app app\n'
                'COPY --from=build /build/target/*.jar /app/app.jar\n'
                'USER app\nENTRYPOINT ["java","-jar","/app/app.jar"]\n')
        elif (folder/'requirements.txt').is_file() and profile.get('backend')=='python':
            version=re.search(r'\bpython\s*(3\.\d+)\b',str(profile.get('runtime_versions','')),re.I)
            if not version:
                pending.append(f'{name}: fijar versión Python y comando de inicio antes del Dockerfile')
                continue
            pending.append(f'{name}: indicar comando de inicio Python validado; no se inventará CMD')
            continue
        else:
            pending.append(f'{name}: aún no hay manifiesto y runtime reproducibles para Dockerfile')
            continue
        rel=folder.relative_to(root)
        prefix=rel.as_posix() if rel.parts else '.'
        path='Dockerfile' if prefix=='.' else prefix+'/Dockerfile'
        ignore='.dockerignore' if prefix=='.' else prefix+'/.dockerignore'
        artifacts[path]=dockerfile
        artifacts[ignore]='node_modules\n.git\n.env\n.env.*\n!.env.example\n.harness\n.aikya\naikya\ndist\ncoverage\n**/__pycache__\n'
    return artifacts,pending


def specs(root: Path, profile: dict) -> tuple[dict[str,str],list[str]]:
    infra=infrastructure(profile)
    files={}
    pending=[]
    environments=infra['environments'] or ['dev']
    iac=infra['iac']
    if iac in ('terraform','opentofu'):
        files['infra/terraform/versions.tf']=(MARK+
            'terraform {\n  required_version = ">= 1.6.0"\n}\n')
        files['infra/terraform/README.md']=('''# Terraform / OpenTofu — plan inicial

Se ha creado únicamente la base de IaC, sin recursos de nube inventados.
Antes de apply: confirmar proveedor, región, cuenta/proyecto, módulos, provider
versionado, backend remoto cifrado y bloqueable, identidad mínima y presupuestos.
No versionar tfstate, .tfvars con secretos ni credenciales.
Nunca ejecutar init contra un backend remoto, plan o apply sin revisar su destino.
''')
        files['infra/terraform/modules/README.md']='# Módulos\n\nAñadir módulos sólo cuando se conozcan recursos y contratos reales.\n'
        for env in environments:
            files[f'infra/terraform/environments/{env}/README.md']=f'# Entorno {env}\n\nConfirmar backend de estado aislado, variables y permisos antes de inicializar.\n'
        pending.append('Terraform/OpenTofu: faltan recursos, provider y backend confirmados; no se generan valores falsos')
    if infra['configuration_management']=='ansible':
        files['infra/ansible/ansible.cfg']=(MARK+
            '[defaults]\ninventory = inventories/dev/hosts.yml\nhost_key_checking = True\nretry_files_enabled = False\n')
        files['infra/ansible/playbooks/site.yml']=(MARK+
            '---\n- name: Configuration management\n  hosts: app\n  gather_facts: false\n  roles:\n    - common\n')
        files['infra/ansible/roles/common/tasks/main.yml']=(MARK+
            '---\n- name: Confirmar variables y hosts antes de configurar\n  ansible.builtin.debug:\n    msg: "Plantilla inicial; aún no se han definido cambios sobre servidores"\n')
        for env in environments:
            files[f'infra/ansible/inventories/{env}/hosts.yml']=(MARK+
                '---\nall:\n  children:\n    app:\n      hosts: {}\n')
        files['infra/ansible/README.md']='# Ansible\n\nInventarios sin hosts reales; completar acceso, gestión de secretos, roles idempotentes y playbooks aprobados antes de ejecutar contra servidores.\n'
        pending.append('Ansible: inventarios vacíos y roles sin cambios sobre hosts; revisión requerida')
    if infra['containers']['enabled']:
        if profile.get('project_type','development')=='development' or infra.get('source_kind')=='source':
            docker,more=dockerfiles(root,profile)
            files.update(docker); pending.extend(more)
        files['infra/docker/README.md']='# Docker\n\nDockerfiles sólo para aplicaciones detectadas con manifiesto y runtime fijado. No ejecutar build/push automáticamente. Configurar puertos, healthchecks y escaneo de dependencias según el servicio real.\n'
        if infra['containers']['compose']:
            services=[]
            port=infra['container_port']
            for name,folder in applications(root,profile):
                relative=folder.relative_to(root).as_posix() or '.'
                dockerfile=('Dockerfile' if relative=='.' else relative+'/Dockerfile')
                if dockerfile in files or (root/dockerfile).is_file():
                    service=[f'  {name}:',f'    build:',f'      context: {relative}',f'      dockerfile: Dockerfile']
                    if port:
                        service += [f'    ports:',f'      - "127.0.0.1:${{APP_PORT:-{port}}}:{port}"']
                    services.extend(service)
            if services:
                files['compose.apps.yaml']=MARK+'services:\n'+'\n'.join(services)+'\n'
            elif infra.get('source_kind')=='image' and infra.get('image_repository'):
                image=infra['image_repository']
                lines=['services:','  app:',f'    image: "{image}"']
                if port:
                    lines.extend(['    ports:',f'      - "127.0.0.1:${{APP_PORT:-{port}}}:{port}"'])
                files['compose.apps.yaml']=MARK+'\n'.join(lines)+'\n'
            else:
                pending.append('Docker Compose: sin Dockerfile validado; generar apps primero y repetir /aikya-infra generate')
    if infra['orchestration']=='kubernetes':
        method=infra['deployment_method']
        if method=='helm' and infra.get('helm_chart_mode')=='existing':
            chart=infra.get('helm_chart_path','')
            if not chart or not (root/chart/'Chart.yaml').is_file():
                pending.append('Helm: chart local no encontrado; confirma helm_chart_path.')
            else:
                pending.append('Helm: reutilizar chart existente '+chart+'; no se sobrescriben sus templates.')
            files['infra/kubernetes/README.md']=(
                '# Helm chart existente\n\n'
                'La estrategia reutiliza el chart local del perfil sin instalarlo. '
                'Revisa values, namespaces, permisos, secrets, probes y rollback.\n')
            return {name:stamp(body) if name.endswith('.md') else body for name,body in files.items()},pending
        files['infra/kubernetes/README.md']=f'# Kubernetes: {method}\n\nRevisar image digest, puertos, secrets, RBAC, recursos, probes, políticas de red y rollback; no conectar a clusters sin autorización.\n'
        image=infra['image_repository'];port=infra['container_port']
        if not (image and port and (':' in image or '@sha256:' in image)):
            pending.append('Kubernetes: se necesita image_repository con tag/digest y container_port confirmados antes de generar manifiestos')
        else:
            deploy=MARK+f'''apiVersion: apps/v1
kind: Deployment
metadata:
  name: app
spec:
  replicas: 1
  selector:
    matchLabels:
      app: app
  template:
    metadata:
      labels:
        app: app
    spec:
      containers:
        - name: app
          image: "{image}"
          ports:
            - containerPort: {port}
          securityContext:
            allowPrivilegeEscalation: false
            capabilities:
              drop: ["ALL"]
          resources:
            requests:
              cpu: 100m
              memory: 128Mi
            limits:
              cpu: 500m
              memory: 512Mi
'''
            service=MARK+f'''apiVersion: v1
kind: Service
metadata:
  name: app
spec:
  type: ClusterIP
  selector:
    app: app
  ports:
    - port: {port}
      targetPort: {port}
'''
            if method in ('yaml','kustomize'):
                files['infra/kubernetes/base/deployment.yaml']=deploy
                files['infra/kubernetes/base/service.yaml']=service
                if method=='kustomize':
                    files['infra/kubernetes/base/kustomization.yaml']=MARK+'apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\nresources:\n  - deployment.yaml\n  - service.yaml\n'
                    for env in environments:
                        files[f'infra/kubernetes/overlays/{env}/kustomization.yaml']=MARK+'apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\nresources:\n  - ../../base\n'
            elif method=='helm':
                name=re.sub(r'[^a-z0-9-]','-',str(profile.get('name','app')).lower()).strip('-')[:55] or 'app'
                chart=f'infra/helm/charts/{name}/'
                files[chart+'Chart.yaml']=MARK+f'apiVersion: v2\nname: {name}\nversion: 0.1.0\nappVersion: "0.1.0"\ntype: application\n'
                files[chart+'values.yaml']=MARK+f'image:\n  repository: "{image}"\nreplicaCount: 1\nservice:\n  port: {port}\n'
                files[chart+'templates/deployment.yaml']=deploy.replace('name: app', 'name: {{ .Release.Name }}').replace('app: app','app: {{ .Release.Name }}').replace('replicas: 1','replicas: {{ .Values.replicaCount }}').replace('image: "'+image+'"','image: "{{ .Values.image.repository }}"').replace('containerPort: '+str(port),'containerPort: {{ .Values.service.port }}')
                files[chart+'templates/service.yaml']=service.replace('name: app','name: {{ .Release.Name }}').replace('app: app','app: {{ .Release.Name }}').replace('port: '+str(port),'port: {{ .Values.service.port }}').replace('targetPort: '+str(port),'targetPort: {{ .Values.service.port }}')
                for env in environments:
                    files[chart+f'values-{env}.yaml']=MARK+'# Valores del entorno; sin secretos ni credenciales.\n'
    return {name:stamp(body) if name.endswith('.md') else body for name,body in files.items()},pending


def plan(root: Path, profile: dict) -> str:
    files,pending=specs(root,profile)
    result=['# Plan Infrastructure & DevOps — Aikya','','**Sólo propuesta. No hay infraestructura desplegada ni comandos remotos ejecutados.**','',
            '## Perfil','', '```json',json.dumps(infrastructure(profile),ensure_ascii=False,indent=2),'```',
            '','## Artefactos propuestos','']
    result += ['- `'+key+'`'+(' (ya existe; se conservará)' if (root/key).exists() else '') for key in sorted(files)] or ['- No se solicitaron recursos de infraestructura.']
    result += ['','## Pendientes y límites','']+[ '- '+x for x in pending] if pending else ['','## Pendientes y límites','','- Sin requisitos de infraestructura adicionales detectados.']
    result+=['','Generación: /aikya-infra generate (pide aprobación y no sobrescribe archivos).',
             'Validación: /aikya-infra validate. No ejecutar apply, destroy, push ni cambios en clusters sin aprobación específica.','']
    return stamp('\n'.join(result))


def sdd_approved(root: Path, profile: dict, spec_id=None, task_id=None) -> bool:
    """Require the selected specification and task; historical approvals do not count."""
    if profile.get("methodology", "standard") != "sdd": return True
    try:
        from aikya.workflows.sdd.engine import require_approved_task
        require_approved_task(root, spec_id, task_id)
        return True
    except (ImportError, ValueError, OSError, TypeError, KeyError):
        return False


def generate(root: Path, profile: dict, approved: bool=False, *, spec_id=None, task_id=None) -> tuple[int,list[str]]:
    if not approved:
        return 2,['Aprobación explícita requerida. Usa generate --approved sólo tras mostrar el plan.']
    if not sdd_approved(root,profile,spec_id,task_id):
        return 2,['SDD requires an approved --spec-id and --task-id before generation.']
    specs_map,pending=specs(root,profile)
    existing=[str(path) for rel in specs_map if (path:=root/rel).exists() and path.is_symlink()]
    existing += [str(path) for rel in specs_map for path in (root/rel).parents if root in (path,*path.parents) and path.is_symlink()]
    if existing:
        return 2,['Rutas simbólicas rechazadas: '+', '.join(sorted(set(existing)))]
    messages=[]
    for rel,body in sorted(specs_map.items()):
        target=root/rel
        if target.exists():
            messages.append('CONSERVADO '+rel)
            continue
        target.parent.mkdir(parents=True,exist_ok=True)
        target.write_text(body,encoding='utf8')
        messages.append('CREADO '+rel)
    messages.extend('PENDIENTE '+x for x in pending)
    return 0,messages


def validate(root: Path, profile: dict, executor=subprocess.run) -> tuple[int,list[str]]:
    """Comprobaciones sin descarga, credenciales, conexiones a clusters ni planes cloud."""
    infra=infrastructure(profile)
    checks=[]
    if infra['iac']=='terraform' and (root/'infra/terraform/versions.tf').is_file():
        checks.append(('Terraform fmt',['terraform','fmt','-check','-recursive','infra/terraform']))
    if infra['iac']=='opentofu' and (root/'infra/terraform/versions.tf').is_file():
        checks.append(('OpenTofu fmt',['tofu','fmt','-check','-recursive','infra/terraform']))
    if infra['configuration_management']=='ansible' and (root/'infra/ansible/playbooks/site.yml').is_file():
        checks.append(('Ansible syntax',['ansible-playbook','-i','infra/ansible/inventories/dev/hosts.yml','--syntax-check','infra/ansible/playbooks/site.yml']))
    if (root/'compose.apps.yaml').is_file():
        checks.append(('Compose config',['docker','compose','-f','compose.apps.yaml','config','--quiet']))
    if infra['orchestration']=='kubernetes':
        method=infra['deployment_method']
        if method=='helm':
            # Comparar siempre rutas resueltas: root puede llegar por un symlink (p. ej. /var -> /private/var en macOS).
            base=root.resolve()
            existing=infra.get('helm_chart_mode')=='existing'
            if existing:
                relative=infra.get('helm_chart_path','')
                chartdir=(root/relative).resolve()
                if not chartdir.is_relative_to(base) or not (chartdir/'Chart.yaml').is_file():
                    return 2,['NOT_CONFIGURED: chart Helm no encontrado o fuera del proyecto.']
                charts=[chartdir/'Chart.yaml']
            else:
                charts=list((root/'infra/helm/charts').glob('*/Chart.yaml')) if (root/'infra/helm/charts').exists() else []
            for chart in charts:
                chartdir=chart.parent.resolve()
                if not chartdir.is_relative_to(base):
                    return 2,['NOT_CONFIGURED: chart Helm no encontrado o fuera del proyecto.']
                chart_rel=chartdir.relative_to(base).as_posix()
                checks.append(('Helm lint',['helm','lint',chart_rel]))
                checks.append(('Helm template',['helm','template','aikya-check',chart_rel]))
        if method=='kustomize' and (root/'infra/kubernetes/base/kustomization.yaml').exists():
            checks.append(('Kustomize build',['kustomize','build','infra/kubernetes/base']))
    results=[]
    errors=0
    if not checks:
        return 2,['NOT_CONFIGURED: no hay artefactos comprobables. Genera o configura la infraestructura antes de validar.']
    for label,command in checks:
        if not shutil.which(command[0]):
            errors+=1;results.append(label+': NOT_CONFIGURED (herramienta ausente)');continue
        try:
            r=executor(command,cwd=root,capture_output=True,text=True,timeout=90,check=False)
        except (OSError,subprocess.TimeoutExpired) as exc:
            errors+=1;results.append(label+': ERROR '+str(exc));continue
        if r.returncode:
            errors+=1;results.append(label+': FAILED '+(r.stderr or r.stdout or 'error')[:250])
        else:
            results.append(label+': PASSED')
    return (1 if errors else 0),results


def main(argv=None) -> int:
    parser=argparse.ArgumentParser(description='Aikya Infrastructure: plan|generate|validate')
    parser.add_argument('action',choices=['plan','generate','validate'])
    parser.add_argument('--target',type=Path,default=ROOT)
    parser.add_argument('--approved',action='store_true')
    parser.add_argument('--spec-id')
    parser.add_argument('--task-id')
    a=parser.parse_args(argv)
    root=a.target.expanduser().resolve()
    try:
        profile=read_profile(root)
        if a.action=='plan':
            print(plan(root,profile));return 0
        if a.action=='generate':
            status,rows=generate(root,profile,a.approved,spec_id=a.spec_id,task_id=a.task_id)
        else:
            status,rows=validate(root,profile)
        print('\n'.join(rows))
        return status
    except (ValueError,OSError,json.JSONDecodeError) as e:
        print('ERROR: '+str(e),file=sys.stderr);return 2


if __name__=='__main__':
    raise SystemExit(main())
