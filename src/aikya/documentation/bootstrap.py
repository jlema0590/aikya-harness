"""Generate localized living docs and language-neutral infrastructure templates."""
from __future__ import annotations
import json
from pathlib import Path
from typing import Any

MARK='<!-- GENERATED BY CLAUDE-DEV-HARNESS -->\n'

def flat(value:Any) -> str:
    return str(value).replace('\\','/').replace('\n',' ').replace('|','/').replace('`',"'").strip()

def pages(profile: dict, modules: list[dict], language: str = "en") -> dict[str, str]:
    """Render only Aikya living docs in the selected language."""
    from aikya.documentation.language import validate
    language = validate(language)
    if language == "es":
        from aikya.documentation.pages_es import pages as localized
    else:
        from aikya.documentation.pages_en import pages as localized
    result = localized(profile, modules)
    if profile.get('methodology', 'odd') == 'sdd':
        from aikya.documentation.layout import stamp, content
        title = 'SDD: specifications and traceability' if language == 'en' else 'SDD: especificaciones y trazabilidad'
        note = ('Explicit approval is required for specification, plan and tasks. Recorded evidence is not an independently executed check.' if language == 'en' else 'La especificación, el plan y las tareas requieren aprobación explícita. Registrar evidencias no equivale a ejecutar comprobaciones independientes.')
        result['aikya/docs/specs/README.md'] = stamp('# ' + title + '\n\n' + note + '\n\n' + ' → '.join('/aikya-' + c for c in ('specify', 'clarify', 'plan', 'tasks', 'implement', 'sdd-status')) + '\n\n' + '`aikya/docs/specs/<project_type>/SPEC-NNN/`\n\n' + ('Nine Aikya SDD roles use only pinned `aikya-template/docs/ai-assisted-development/README.md`. Show a starter with `sdd_engine.py templates --template <name>`. Review template fields before writing; omitted sections do not create empty documents.' if language=='en' else 'Nueve roles SDD de Aikya utilizan únicamente `aikya-template/docs/ai-assisted-development/README.md`. Consulta una plantilla con `sdd_engine.py templates --template <nombre>`. Revisa los campos antes de escribir; las secciones omitidas no generan documentos vacíos.'))
        result['aikya/docs/README.md'] = stamp(content(result['aikya/docs/README.md'])+'\n\n- [' + title + '](specs/README.md)')
    return result


def _infra_files(p:dict) -> dict[str,str]:
    if p.get('project_type','development')!='development':
        return {'.gitignore': (
            '# Estado, credenciales e infraestructura local Aikya\n'
            '.harness/state/\n.harness/welcome.json\n'
            '.env\n.env.*\n!.env.example\n'
            '**/.terraform/\n**/*.tfstate\n**/*.tfstate.*\n'
            '**/*.tfvars\n**/*.tfvars.json\n**/.ansible/\n')}
    outputs={}
    if p.get('repository_layout', 'monorepo') == 'monorepo':
        outputs['apps/README.md']='''# Monorepo applications\n\nProject generators create modules under `apps/api`, `apps/web`, `apps/frontend`, `apps/mobile`, `apps/android` y/o `apps/ios` according to the profile. This folder does not prove that modules have been generated or verified.\n'''
        outputs['packages/README.md']='''# Shared packages\n\nKeep only libraries, contracts and utilities justified for multiple modules. Do not share persistence entities or secrets directly. Document and test public APIs before publishing.\n'''
        outputs['contracts/README.md']='''# Contracts and compatibility\n\nMaintain versioned REST/OpenAPI, GraphQL or gRPC contracts when needed, with compatibility tests. Do not invent interfaces without endpoint requirements.\n'''
    js_app=(p['backend'] in ('node','next') or p['frontend'] in ('react','vue','angular') or p['mobile_framework']=='react-native')
    if js_app and p.get('repository_layout','monorepo') == 'monorepo':
        import re
        package_name=re.sub(r'[^a-z0-9-]','-',p['name'].lower()).strip('-') or 'application'
        pkg={'name':package_name+'-workspace','private':True,'version':'0.0.0','scripts':{
            'harness:docs':'python3 aikya/scripts/harness/docs_guard.py base',
            'harness:verify':'python3 aikya/scripts/harness/run_checks.py'}}
        if p['package_manager'] != 'pnpm':
            pkg['workspaces']=['apps/*','packages/*']
        else:
            outputs['pnpm-workspace.yaml']="packages:\n  - 'apps/*'\n  - 'packages/*'\n"
        outputs['package.json']=json.dumps(pkg,ensure_ascii=False,indent=2)+'\n'
    database=p['database']
    services={
        'postgresql':('postgres:17','5432:5432','postgres',
            'POSTGRES_USER: ${POSTGRES_USER:-app}\n      POSTGRES_PASSWORD: ${POSTGRES_PASSWORD:?define_POSTGRES_PASSWORD}\n      POSTGRES_DB: ${POSTGRES_DB:-app}'),
        'mysql':('mysql:8.4','3306:3306','mysql',
            'MYSQL_USER: ${MYSQL_USER:-app}\n      MYSQL_PASSWORD: ${MYSQL_PASSWORD:?define_MYSQL_PASSWORD}\n      MYSQL_ROOT_PASSWORD: ${MYSQL_ROOT_PASSWORD:?define_MYSQL_ROOT_PASSWORD}\n      MYSQL_DATABASE: ${MYSQL_DATABASE:-app}'),
        'mongodb':('mongo:7','27017:27017','mongo',
            'MONGO_INITDB_ROOT_USERNAME: ${MONGO_USERNAME:?define_MONGO_USERNAME}\n      MONGO_INITDB_ROOT_PASSWORD: ${MONGO_PASSWORD:?define_MONGO_PASSWORD}'),
    }
    if database in services:
        image,port,svc,env=services[database]
        outputs['compose.yaml']=f'''# Local development dependencies only. NOT a production deployment manifest.
# Bind database ports to loopback and load secrets from an untracked local .env file.
services:
  {svc}:
    image: {image}
    restart: unless-stopped
    ports:
      - "127.0.0.1:{port}"
    environment:
      {env}
    volumes:
      - db_data:/data/db
volumes:
  db_data:
'''
        if database in ('postgresql','mysql'):
            outputs['compose.yaml']=outputs['compose.yaml'].replace('db_data:/data/db',
                'db_data:/var/lib/postgresql/data' if database=='postgresql' else 'db_data:/var/lib/mysql')
    else:
        outputs['infra/docker/compose.example.yaml']='''# Example only: add services after verifying runtimes, ports and secret handling.
services: {}
'''
    outputs['infra/docker/README.md']='''# Docker y contenedores

compose.yaml, if present, defines local development dependencies only and does not deploy the application.
Generate per-module Dockerfiles only after application source and runtime versions exist. Add health checks, a non-root user, scanning and efficient layers. Avoid production default credentials.
'''
    outputs['infra/observability/README.md']='''# OpenTelemetry — integration pending

This directory contains guidance, **not running instrumentation**. Integrate approved SDKs with W3C tracecontext, resource attributes (service.name and deployment.environment) and OTLP export. Exclude secrets and PII. Validate against an authorized collector before enabling alerts.

Typical variables (only if the application is instrumented): `OTEL_SERVICE_NAME`, `OTEL_EXPORTER_OTLP_ENDPOINT`, `OTEL_TRACES_EXPORTER`, `OTEL_METRICS_EXPORTER`.
'''
    outputs['infra/observability/otel.env.example']='''# Example variables; they are not loaded automatically.
OTEL_SERVICE_NAME=replace-with-service-name
OTEL_EXPORTER_OTLP_ENDPOINT=http://localhost:4318
OTEL_TRACES_EXPORTER=otlp
OTEL_METRICS_EXPORTER=otlp
'''
    outputs['.env.example']='''# Local development: copy to .env (NEVER commit the .env file).
# Configure variables for the selected database; never use these defaults in production.
POSTGRES_USER=app
POSTGRES_DB=app
POSTGRES_PASSWORD=REPLACE_LOCALLY
MYSQL_USER=app
MYSQL_DATABASE=app
MYSQL_PASSWORD=REPLACE_LOCALLY
MYSQL_ROOT_PASSWORD=REPLACE_LOCALLY
MONGO_USERNAME=app
MONGO_PASSWORD=REPLACE_LOCALLY
'''
    outputs['.gitignore']='''# Harness and local work state
.harness/state/
.harness/welcome.json
# Environments and credentials
.env
.env.*
!.env.example
# Common build artifacts
graphify-out/
node_modules/
dist/
build/
target/
**/bin/
**/obj/
.next/
.dart_tool/
'''
    if p['ci']=='github-actions':
        outputs['.github/workflows/harness.yml']='''name: Harness quality gates
on:
  pull_request:
  push:
    branches: [main]
permissions:
  contents: read
jobs:
  docs:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0
      - uses: actions/setup-python@v5
        with:
          python-version: '3.11'
      - name: Validate documentation structure
        run: python3 aikya/scripts/harness/docs_guard.py base
      - name: Validate change documentation
        if: github.event_name == 'pull_request'
        env:
          BASE_SHA: ${{ github.event.pull_request.base.sha }}
        run: python3 aikya/scripts/harness/docs_guard.py ci --base "$BASE_SHA"
  # Add stack-specific jobs for SDK setup and real quality checks.
  # run_checks.py requires real runtimes and dependencies; do not assume them on the Python runner.
'''
    return outputs


def infra_files(profile: dict) -> dict[str,str]:
    from aikya.documentation.layout import stamp
    return {name:stamp(body) if name.endswith('.md') else body for name,body in _infra_files(profile).items()}
