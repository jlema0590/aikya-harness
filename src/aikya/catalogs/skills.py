"""Inventario reproducible de Agent Skills activas en este proyecto.

El inventario describe disponibilidad/configuración, NO invocaciones reales del modelo.
Nunca descarga dependencias ni examina repositorios fuera del proyecto.
"""
from __future__ import annotations
import json
import re
from pathlib import Path

MARKER = '<!-- GENERATED BY AIKYA-HARNESS: skills-registry -->'
BUILTIN = {'ponytail', 'graphify', 'ui-ux-pro-max'}


def _plain(value: object) -> str:
    return str(value).replace('\\', '/').replace('\n', ' ').replace('|', '/').replace('`', "'").strip()[:350]


def _metadata(file: Path) -> tuple[str, str]:
    try:
        data = file.read_text(encoding='utf8')[:12000]
    except (OSError,UnicodeError):
        return file.parent.name, 'Descripción no disponible'
    if not data.startswith('---\n'):
        return file.parent.name, 'Sin cabecera Agent Skills'
    fm=data.split('---\n',2)[1]
    get=lambda key: next((m.group(1).strip(' \'"') for ln in fm.splitlines()
                         if (m:=re.match(r'^'+key+r':\s*(.*?)\s*$',ln))), '')
    return get('name') or file.parent.name, get('description') or 'Sin descripción'


def render(root: Path, profile: dict|None=None, language: str|None=None) -> str:
    """Enumera skills locales y estados de integraciones con traza de procedencia."""
    root=root.resolve()
    from aikya.documentation.layout import stamp
    from aikya.documentation.language import resolve as documentation_language
    from aikya.documentation.language import validate as validate_docs_language
    if (validate_docs_language(language) if language is not None else documentation_language(root)) == "en":
        return stamp(_render_english(root))
    profile=profile or {}
    skill_root=root/'.claude/skills'
    discovered: dict[str,tuple[str,str]] = {}
    if skill_root.is_dir() and not skill_root.is_symlink():
        for folder in sorted(skill_root.iterdir()):
            if folder.is_symlink() or not folder.is_dir():
                continue
            file=folder/'SKILL.md'
            if file.is_file() and not file.is_symlink():
                discovered[folder.name]=_metadata(file)
    lock={}
    path=root/'.harness/external-skills-lock.json'
    if path.is_file() and not path.is_symlink():
        try:
            data=json.loads(path.read_text(encoding='utf8'))
            if isinstance(data.get('skills'),dict): lock=data['skills']
        except (OSError,ValueError,TypeError):
            pass
    engineering={}
    manifest=root/'.harness/engineering-catalog.json'
    if manifest.is_file() and not manifest.is_symlink():
        try:
            payload=json.loads(manifest.read_text(encoding='utf8'))
            if payload.get('_generated_by')=='aikya-engineering-catalog' and isinstance(payload.get('files'),dict):
                engineering=payload['files']
        except (ValueError,OSError,TypeError):
            pass
    rows=[]
    names=sorted(set(discovered)|set(lock))
    for folder in names:
        description=discovered.get(folder,('', ''))[1]
        item=lock.get(folder,{})
        if not isinstance(item,dict): item={}
        installed=folder in discovered
        catalog_key=f'.claude/skills/{folder}/SKILL.md'
        kind=('Externa' if folder in BUILTIN or folder in lock else
              'Aikya Engineering' if catalog_key in engineering else
              'Aikya' if folder.startswith('aikya-') else 'Proyecto')
        source=item.get('source') or item.get('location') or ('Aikya / paquete técnico revisado' if kind=='Aikya Engineering' else 'Fuente Aikya' if kind=='Aikya' else 'Local')
        state='Disponible' if installed else 'No disponible'
        if not installed and item.get('state')=='failed': state='Falló instalación'
        rows.append(f'| `/{_plain(folder)}` | {_plain(kind)} | {_plain(state)} | {_plain(source)} | {_plain(description or item.get("detail") or "No instalada")} |')
    for name in sorted(BUILTIN-set(lock)-set(discovered)):
        # Pendientes por defecto no se presentan como skills activas.
        pass
    rows='\n'.join(rows) or '| — | — | Sin skills locales inventariadas | — | — |'
    return stamp(f'''{MARKER}
# Skills utilizadas y disponibles — Aikya Harness

Este inventario describe las **skills registradas en el proyecto** y su disponibilidad para Claude Code. **No es un histórico de invocaciones**: una skill instalada puede no haberse ejecutado nunca. La selección contextual evita cargar skills no pertinentes.

- Perfil técnico: `.harness/project-profile.json`.
- Skills locales: `.claude/skills/<nombre>/SKILL.md`.
- Skills globales del usuario: pueden estar disponibles para Claude Code, pero no se atribuyen al proyecto sin registrarlas localmente.
- Origen y versión de instalaciones externas: `.harness/external-skills-lock.json` (estado local, no versionar).

## Skills del proyecto

| Comando / skill | Tipo | Estado | Origen | Función |
|---|---|---|---|---|
{rows}

## Política de gestión

- `/aikya-skills-status`: consultar y sincronizar el inventario.
- `/aikya-skills-plan`: estudiar fuentes, permisos, versión y repercusiones sobre el stack.
- `/aikya-install-skill`: instalar únicamente tras aprobación y actualizar esta tabla.
- Las skills externas son código de terceros: revisar licencia, contenido, procedencia y permisos antes de instalarlas.
- Registrar el uso **real** sólo si existen evidencias de ejecución; nunca inferirlo por la mera presencia de un archivo.
''')


def _render_english(root: Path) -> str:
    """Produce the English inventory without losing lockfile provenance."""
    root = root.resolve()
    skill_root = root / ".claude/skills"
    lock = {}
    lock_file = root / ".harness/external-skills-lock.json"
    if lock_file.is_file() and not lock_file.is_symlink():
        try:
            obj = json.loads(lock_file.read_text(encoding="utf8"))
            if isinstance(obj.get("skills"), dict):
                lock = obj["skills"]
        except (OSError, ValueError, TypeError):
            pass
    engineering = {}
    manifest = root / ".harness/engineering-catalog.json"
    if manifest.is_file() and not manifest.is_symlink():
        try:
            obj = json.loads(manifest.read_text(encoding="utf8"))
            if isinstance(obj.get("files"), dict):
                engineering = obj["files"]
        except (OSError, ValueError, TypeError):
            pass
    discovered = {}
    if skill_root.is_dir() and not skill_root.is_symlink():
        for folder in sorted(skill_root.iterdir()):
            if folder.is_symlink() or not folder.is_dir():
                continue
            path = folder / "SKILL.md"
            if path.is_file() and not path.is_symlink():
                discovered[folder.name] = _metadata(path)[1]
    rows = []
    for name in sorted(set(discovered) | set(lock)):
        item = lock.get(name, {})
        if not isinstance(item, dict):
            item = {}
        available = name in discovered
        state = "Available" if available else "Not available"
        if not available and item.get("state") == "failed":
            state = "Installation failed"
        kind = ("External" if name in BUILTIN or name in lock else
                "Aikya Engineering" if ".claude/skills/" + name + "/SKILL.md" in engineering else
                "Aikya" if name.startswith("aikya-") else "Project")
        source = item.get("source") or item.get("location") or (
            "Aikya vetted technical bundle" if kind == "Aikya Engineering" else
            "Aikya source" if kind == "Aikya" else "Local")
        desc = discovered.get(name) or item.get("detail") or "Not installed"
        safe = lambda value: str(value).replace("|", "/").replace("\n", " ").strip()
        rows.append("| /" + safe(name) + " | " + kind + " | " + state + " | "
                    + safe(source) + " | " + safe(desc) + " |")
    table = "\n".join(rows) or "| — | — | No local skills found | — | — |"
    return (MARKER + "\n# Installed and available Agent Skills\n\n"
            "This lists registered project skills, not a history of model invocations. "
            "A present skill may never have been invoked.\n\n"
            "## Project skills\n\n| Command | Type | Status | Source | Purpose |\n"
            "|---|---|---|---|---|\n" + table + "\n\n"
            "## Governance\n\n"
            "- /aikya-skills-status: inspect registrations.\n"
            "- /aikya-skills-plan: review provenance and permissions.\n"
            "- /aikya-install-skill: install only after explicit authorization.\n"
            "- Verify licenses and source integrity for external skills.\n"
            "- Never infer execution from installation alone.\n")


def write_inventory(root: Path, profile: dict|None=None) -> tuple[bool,str]:
    from aikya.documentation.layout import safe, generated, stamp, write_document
    try:target=safe(root,'skills.md')
    except ValueError:return False,'Symlinked documentation path preserved'
    if target.exists() and not generated(target.read_text(encoding='utf8')):
        return False, 'aikya/docs/skills.md personalizado: requiere actualización manual'
    present=any(p.is_file() and not p.is_symlink() for p in (root/'.claude/skills').glob('*/SKILL.md'))
    lock=root/'.harness/external-skills-lock.json'
    if not present and not lock.is_file():return True,'No skill inventory data; no document created'
    content=stamp(render(root,profile))
    if target.exists() and target.read_text(encoding='utf8')==content:
        return True,'aikya/docs/skills.md sin cambios'
    write_document(root,'skills.md',content,replace_generated=True)
    return True,'aikya/docs/skills.md actualizado'
