#!/usr/bin/env python3
"""Aikya engineering add-ons (local, curated and stack-aware).

Only files bundled in the trusted Aikya distribution. No network, shell,
executables or user-provided paths. Never clobber customized agents/skills.
"""
from __future__ import annotations
from aikya.resource_paths import source_root,source_path
import argparse
import hashlib
import json
from pathlib import Path

HERE = source_root()
AGENTS = {
    'orchestrator', 'planner', 'astro-tailwind-developer', 'flutter-developer',
    'node-backend-developer', 'vue-developer', 'cicd-engineer', 'cloud-architect',
    'docker-developer', 'nextjs-developer', 'code-reviewer', 'test-engineer',
    'clean-architecture-architect', 'event-driven-architect',
    'layered-architecture-architect', 'microservices-architect', 'monolith-architect',
    'angular-developer', 'dotnet-developer', 'java-developer', 'kotlin-developer',
    'python-developer', 'react-developer',
    'terraform-engineer', 'ansible-engineer', 'kubernetes-engineer', 'helm-engineer', 'log-summarizer',
    'aikya-auxiliary-analyzer', 'aikya-docs-assistant',
}
SKILLS = {
    'astro-performance', 'cicd-pipelines', 'cloud-architecture', 'cloud-security',
    'code-review', 'docker-best-practices', 'finops-optimization',
    'flutter-architecture', 'kubernetes-operations', 'nextjs-architecture',
    'node-api-design', 'security-audit', 'terraform-iac', 'testing-strategy',
    'vue-architecture',
    'angular-engineering', 'clean-architecture', 'dotnet-engineering',
    'event-driven-architecture', 'java-engineering', 'kotlin-engineering',
    'layered-architecture', 'microservices-architecture',
    'modular-monolith-architecture', 'python-engineering', 'react-engineering',
    'ansible-automation', 'helm-deployment', 'kustomize-deployment',
}
BASE_AGENTS = {'planner', 'code-reviewer', 'test-engineer'}
BASE_SKILLS = {'code-review', 'security-audit', 'testing-strategy'}
MARKER = '<!-- GENERATED BY AIKYA-HARNESS: engineering-agents -->'


def _manifest(root: Path) -> Path:
    return root / '.harness/engineering-catalog.json'


def _old_state(root: Path) -> dict:
    path = _manifest(root)
    if not path.is_file() or path.is_symlink():
        return {}
    try:
        obj = json.loads(path.read_text(encoding='utf-8'))
        return obj if isinstance(obj, dict) and obj.get('_generated_by') == 'aikya-engineering-catalog' else {}
    except (ValueError, OSError):
        return {}


def discover(root: Path, profile: dict, modules: list[dict] | None = None) -> dict[str, list[str]]:
    """Choose only relevant technologies; optional specialisms remain in catalog."""
    root = Path(root)
    modules = modules or []
    b = profile.get('backend', 'none')
    f = profile.get('frontend', 'none')
    mobile = profile.get('mobile', 'none')
    framework = profile.get('mobile_framework', 'none')
    stacks = {str(m.get('technology', '')).lower() for m in modules if isinstance(m, dict)}
    if profile.get('project_type','development')!='development':
        b=f=mobile=framework='none'
        stacks=set()
        modules=[]
    patterns = profile.get('architecture_patterns', [])
    if not isinstance(patterns, list):
        patterns = []
    agents, skills = set(BASE_AGENTS), set(BASE_SKILLS)
    # Architecture and programming language are independent dimensions.
    # Only activate architectural choices explicitly made during the interview.
    architecture = ('undecided' if profile.get('project_type','development')!='development' else profile.get('architecture','undecided'))
    architectural = {
        'clean': ('clean-architecture-architect', 'clean-architecture'),
        'layered': ('layered-architecture-architect', 'layered-architecture'),
        'modular-monolith': ('monolith-architect', 'modular-monolith-architecture'),
        'microservices': ('microservices-architect', 'microservices-architecture'),
    }
    if architecture in architectural:
        agent, skill = architectural[architecture]
        agents.add(agent); skills.add(skill)
    if 'event-driven' in patterns:
        agents.add('event-driven-architect'); skills.add('event-driven-architecture')
    languages = {
        'java': ('java-developer', 'java-engineering'),
        'dotnet': ('dotnet-developer', 'dotnet-engineering'),
        'python': ('python-developer', 'python-engineering'),
        'react': ('react-developer', 'react-engineering'),
        'angular': ('angular-developer', 'angular-engineering'),
    }
    for tech, (agent, skill) in languages.items():
        if b == tech or f == tech or tech in stacks or (tech == 'react' and b == 'next'):
            agents.add(agent); skills.add(skill)
    if profile.get('android_language') == 'kotlin' and profile.get('mobile_framework') == 'native' and profile.get('mobile') in ('android', 'both'):
        agents.add('kotlin-developer'); skills.add('kotlin-engineering')
    if 'kotlin' in stacks:
        agents.add('kotlin-developer'); skills.add('kotlin-engineering')
    if b == 'node' or 'node' in stacks:
        agents.add('node-backend-developer'); skills.add('node-api-design')
    if b == 'next' or 'next' in stacks:
        agents.add('nextjs-developer'); skills.add('nextjs-architecture')
    if f == 'vue' or 'vue' in stacks:
        agents.add('vue-developer'); skills.add('vue-architecture')
    if framework == 'flutter' or 'flutter' in stacks:
        agents.add('flutter-developer'); skills.add('flutter-architecture')
    # Astro is not an interview choice but may exist in repositories already.
    astro = (profile.get('project_type','development')=='development' and
             (any((root / x).is_file() for x in ('astro.config.mjs', 'astro.config.ts', 'astro.config.js')) or 'astro' in stacks))
    if astro:
        agents.add('astro-tailwind-developer'); skills.add('astro-performance')
    ci = profile.get('ci', 'none')
    if ci not in ('none', 'undecided', None):
        agents.add('cicd-engineer'); skills.add('cicd-pipelines')
    deployment = profile.get('deployment', 'none')
    if deployment in ('docker', 'kubernetes'):
        agents.add('docker-developer'); skills.add('docker-best-practices')
    if deployment == 'kubernetes':
        skills.add('kubernetes-operations')
    if deployment in ('cloud-managed', 'serverless', 'kubernetes'):
        agents.add('cloud-architect'); skills.add('cloud-architecture')
    # Especialistas opcionales elegidos explícitamente en la entrevista DevOps.
    from aikya.discovery.infrastructure import validated as validate_infrastructure
    infra = validate_infrastructure(profile)
    if infra['iac'] in ('terraform','opentofu'):
        agents.add('terraform-engineer');skills.add('terraform-iac')
    if infra['configuration_management']=='ansible':
        agents.add('ansible-engineer');skills.add('ansible-automation')
    if infra['containers']['enabled']:
        agents.add('docker-developer');skills.add('docker-best-practices')
    if infra['orchestration']=='kubernetes':
        agents.add('kubernetes-engineer');skills.add('kubernetes-operations')
        if infra['deployment_method']=='helm':
            agents.add('helm-engineer');skills.add('helm-deployment')
        if infra['deployment_method']=='kustomize':
            skills.add('kustomize-deployment')
    if infra['provider'] in ('aws','azure','gcp','hybrid'):
        agents.add('cloud-architect');skills.add('cloud-architecture')
    if len(modules) > 1 or profile.get('architecture') in ('microservices', 'modular-monolith'):
        agents.add('orchestrator')
    # v1 opt-in keeps its legacy Haiku 4.5 behavior without an automatic upgrade.
    # New v2 auxiliaries require explicit approval, a suitable CLI and provider.
    try:
        from aikya.routing.policy import validated, auxiliary_ready
        policy_path = root / '.aikya/model-policy.json'
        if policy_path.is_file() and not policy_path.is_symlink():
            model_policy = validated(json.loads(policy_path.read_text(encoding='utf8')))
            if model_policy['schema_version'] == 1:
                if model_policy['auxiliary_enabled'] and model_policy['user_approved']:
                    agents.add('log-summarizer')
            elif auxiliary_ready(model_policy):
                from aikya.routing.models import inspect_cli, capability_status
                status = capability_status(model_policy, inspect_cli().get('version'))
                if status['ready_for_cli_delegation']:
                    tasks = set(model_policy['allowed_tasks'])
                    if tasks & {'extraction', 'classification', 'routing'}:
                        agents.add('aikya-auxiliary-analyzer')
                    if 'documentation' in tasks:
                        agents.add('aikya-docs-assistant')
                    if 'log-summary' in tasks:
                        agents.add('log-summarizer')
    except (ValueError, UnicodeError, OSError):
        pass  # Invalid/unavailable policy may never silently enable an auxiliary.
    return {'agents': sorted(agents & AGENTS), 'skills': sorted(skills & SKILLS)}


def _digest(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def _destination(root: Path, kind: str, name: str) -> Path:
    if kind == 'agents':
        return root / '.claude/agents' / (name + '.md')
    return root / '.claude/skills' / name / 'SKILL.md'


def install_selected(root: Path, selection: dict[str, list[str]], source: Path | None = None) -> list[str]:
    """Install vetted names only. Idempotent; preserve customized paths."""
    root = Path(root).resolve()
    source = Path(source or (source_path(HERE, 'engineering'))).resolve()
    state = _old_state(root)
    previous = state.get('files', {}) if isinstance(state.get('files'), dict) else {}
    new = dict(previous)
    logs = []
    for kind, allowed in (('agents', AGENTS), ('skills', SKILLS)):
        for name in sorted(set(selection.get(kind, []))):
            if name not in allowed:
                raise ValueError(f'No está en el catálogo permitido: {kind}/{name}')
            relative = (Path(kind) / (name + '.md')) if kind == 'agents' else (Path(kind) / name / 'SKILL.md')
            original = source / relative
            if not original.is_file() or original.is_symlink():
                raise FileNotFoundError(f'Falta add-on distribuido: {original}')
            # A resolved descendant check prevents out-of-root symlink tricks.
            dest = _destination(root, kind, name)
            if any(x.is_symlink() for x in (dest, *dest.parents) if x != root.parent and root in (x, *x.parents)):
                logs.append(f'CONSERVADO enlace simbólico: {dest}')
                continue
            raw = original.read_bytes()
            if kind == 'agents':
                # v6 configures only generated agents; never overwrite custom files.
                try:
                    from aikya.routing.policy import validated, resolved_agent_model
                    policy_path = root / '.aikya/model-policy.json'
                    policy = validated(json.loads(policy_path.read_text(encoding='utf8'))
                                       if policy_path.is_file() and not policy_path.is_symlink() else None)
                    if (policy['schema_version'] == 2 and policy['auxiliary_enabled'] and
                            name in {'aikya-auxiliary-analyzer','aikya-docs-assistant','log-summarizer'}):
                        from aikya.routing.models import inspect_cli, capability_status
                        if not capability_status(policy, inspect_cli().get('version'))['ready_for_cli_delegation']:
                            policy = {**policy, 'model_access_confirmed': False}
                    import re
                    text = raw.decode('utf8')
                    text = re.sub(r'(?m)^model:\s*[^\n]+$', 'model: ' + resolved_agent_model(name, policy), text, count=1)
                    raw = text.encode('utf8')
                except (OSError, UnicodeError, ValueError) as exc:
                    logs.append(f'AVISO model policy: {exc}')
            from aikya.documentation.layout import asset_bytes
            raw=asset_bytes(dest,raw)
            key = dest.relative_to(root).as_posix()
            if dest.exists():
                if not dest.is_file():
                    logs.append(f'CONSERVADO objeto existente: {dest}'); continue
                current = dest.read_bytes()
                if current != raw and _digest(current) != previous.get(key):
                    logs.append(f'CONSERVADO personalizado: {dest}'); continue
                if current == raw:
                    new[key] = _digest(current)
                    logs.append(f'DISPONIBLE {kind}/{name}')
                    continue
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(raw)
            new[key] = _digest(raw)
            logs.append(f'INSTALADO {kind}/{name}')
    manifest = _manifest(root)
    if manifest.is_symlink() or manifest.parent.is_symlink():
        raise ValueError('Manifest o carpeta simbólica no permitida')
    manifest.parent.mkdir(parents=True, exist_ok=True)
    manifest.write_text(json.dumps({'_generated_by':'aikya-engineering-catalog', 'files':new, 'source':'Aikya curated technical bundle; no network'}, indent=2, ensure_ascii=False)+'\n',encoding='utf8')
    write_agents_doc(root)
    # Synchronize skills registry only if installed. Do not overwrite user docs.
    try:
        from aikya.catalogs.skills import write_inventory
    except ImportError:
        write_inventory = None
    if write_inventory:
        ok, msg = write_inventory(root)
        logs.append(('INVENTARIO ' if ok else 'AVISO ') + msg)
    return logs


def write_agents_doc(root: Path) -> None:
    from aikya.documentation.layout import safe, write_document
    target = safe(root, 'tools/agents.md')
    if target.is_symlink() or target.parent.is_symlink():
        return
    from aikya.documentation.layout import generated, stamp, update_index
    if target.exists() and not generated(target.read_text(encoding='utf8')):
        return
    from aikya.documentation.language import resolve as docs_language
    english = docs_language(root) == "en"
    rows = []
    for name in sorted(AGENTS):
        path = _destination(root, "agents", name)
        if path.is_file() and not path.is_symlink():
            rows.append(f"| {name} | " + ("Available" if english else "Disponible")
                        + " | Aikya Engineering |")
    if english:
        if (root/".claude/agents/security-reviewer.md").is_file():
            rows.append("| security-reviewer | Existing Aikya agent | Preserved, not duplicated |")
        body = (MARKER + "\n# Available engineering agents\n\n"
                "Agents are selected according to the project's real technology stack. "
                "Available does not mean invoked.\n\n"
                "| Agent | Status | Provenance |\n|---|---|---|\n"
                + "\n".join(rows) + "\n")
    else:
        if (root/".claude/agents/security-reviewer.md").is_file():
            rows.append("| security-reviewer | Agente Aikya existente | Se conserva, no se duplica |")
        body = (MARKER + "\n# Agentes técnicos disponibles\n\n"
                "Catálogo seleccionado por stack; disponible no equivale a invocado.\n\n"
                "| Agente | Estado | Procedencia |\n|---|---|---|\n"
                + "\n".join(rows) + "\n")
    if rows:
        write_document(root, 'tools/agents.md', body, replace_generated=True)

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description='Catálogo técnico local Aikya (invocado desde Claude Code)')
    parser.add_argument('action', choices=('list','plan','install'))
    parser.add_argument('--root', type=Path, default=Path.cwd())
    parser.add_argument('--names', default='', help='Nombres de skills/agentes separados por coma')
    parser.add_argument('--approved', action='store_true')
    args = parser.parse_args(argv)
    root = args.root.resolve()
    if args.action == 'list':
        print(json.dumps({'agents':sorted(AGENTS), 'skills':sorted(SKILLS)},ensure_ascii=False,indent=2));return 0
    choices = [x.strip() for x in args.names.split(',') if x.strip()]
    selected = {'agents': [x for x in choices if x in AGENTS], 'skills':[x for x in choices if x in SKILLS]}
    unknown = set(choices) - AGENTS - SKILLS
    if unknown:
        parser.error('Nombres fuera del catálogo: '+', '.join(sorted(unknown)))
    if not choices:
        profile_path=root/'.harness/project-profile.json'
        if not profile_path.is_file():parser.error('Falta perfil del proyecto; usa /aikya-init para nuevo o /aikya-analyze para existente')
        profile=json.loads(profile_path.read_text(encoding='utf8'))
        selected=discover(root,profile.get('decisions',{}),profile.get('detected',{}).get('modules',[]))
    if args.action=='plan':
        print(json.dumps(selected,ensure_ascii=False,indent=2));return 0
    if not args.approved:
        parser.error('Instalación necesita autorización explícita desde Claude Code (--approved)')
    for line in install_selected(root,selected):print(line)
    return 0

if __name__=='__main__':
    raise SystemExit(main())
