HISTORICAL_GALLERY=Path('examples/documentation/generated')
SOURCE_GALLERY='https://github.com/jlema0590/aikya-harness/blob/08db4879ae3a8697c91adb0cc46bd76e333c693b/examples/documentation/generated/README.es.md'


def files_to_copy(source:Path):
    for asset in runtime_assets(source,'registration'):
        yield asset,asset.destination


from aikya.installation.assets import runtime_asset_bytes


def retire_historical_gallery(runtime:Path,previous:dict[str,str],logs:list[str])->None:
    """Retire only recorded unchanged examples, with verified recoverable backups."""
    guide=runtime/'examples/documentation/README.md'
    if guide.is_file() and not any(p.is_symlink() for p in (guide,*guide.parents)):
        raw=guide.read_bytes()
        if b'](generated/README.es.md)' in raw:
            logs.append('PRESERVED historical gallery: customized guide retains local navigation')
            return
    prepared=[]
    for name,digest in sorted(previous.items()):
        relative=Path(name)
        if not relative.is_relative_to(HISTORICAL_GALLERY) or relative==HISTORICAL_GALLERY:continue
        if relative.is_absolute() or '..' in relative.parts or relative.as_posix()!=name:
            logs.append('PRESERVED unsafe historical gallery record');continue
        path=runtime/relative;backup=runtime/'retired-assets'/relative
        candidates=(path,backup,*path.parents,*backup.parents)
        if any(p.is_symlink() for p in candidates):
            logs.append('PRESERVED symlinked historical gallery path: '+name);continue
        if not path.exists():continue
        if not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest()!=digest:
            logs.append('PRESERVED customized historical gallery file: '+name);continue
        raw=path.read_bytes()
        if backup.exists() and (not backup.is_file() or backup.read_bytes()!=raw):
            raise ValueError('Conflicting historical gallery backup: '+name)
        prepared.append((name,path,backup,raw))
    from aikya.storage import atomic_write
    for name,path,backup,raw in prepared:
        if path.read_bytes()!=raw:raise ValueError('Historical gallery changed since preflight: '+name)
        if not backup.exists():atomic_write(backup,raw)
        path.unlink();previous.pop(name,None)
        logs.append('RETIRED managed historical gallery file with backup: '+name)
        parent=path.parent
        while parent.is_relative_to(runtime/HISTORICAL_GALLERY):
            try:parent.rmdir()
            except OSError:break
            parent=parent.parent


def managed_copy(src:Path,dst:Path,root:Path,logs:list[str]):
    if isinstance(src,Path) and not src.is_file(): raise FileNotFoundError(src)
    for candidate in (dst, *list(dst.parents)):
        if candidate == root.parent:
            break
        if candidate.is_symlink():
            raise ValueError(f'Symlink rejected: {candidate}')
    rendered=runtime_asset_bytes(dst.relative_to(root),src.read_bytes())
    if dst.exists():
        if dst.read_bytes()==rendered:
            logs.append(f'IGUAL {dst}')
            return
        # Only update content generated by a previous Aikya version.
        marker=root/'manifest.json'
        if not marker.is_file():
            logs.append(f'PRESERVED CUSTOM {dst}')
            return
        previous=json.loads(marker.read_text(encoding='utf8')).get('files',{})
        key=dst.relative_to(root).as_posix()
        old=previous.get(key)
        if not old or hashlib.sha256(dst.read_bytes()).hexdigest()!=old:
            logs.append(f'CONSERVADO PERSONALIZADO {dst}')
            return
    dst.parent.mkdir(parents=True,exist_ok=True)
    dst.write_bytes(rendered)
    shutil.copymode(src,dst) if isinstance(src,Path) else None
    logs.append(f'INSTALADO {dst}')


def verified_skill_upgrade(destination,source,previous_hash=None):
    """A marker is not proof of ownership after local editing."""
    from aikya.documentation.migration_hashes import ASSETS
    raw=destination.read_bytes();digest=hashlib.sha256(raw).hexdigest()
    record=ASSETS.get('.claude/skills/'+destination.parent.name+'/SKILL.md',{})
    return raw==asset_bytes(destination,source.read_bytes()) or digest==previous_hash or digest==record.get('sha256') or digest in record.get('variants',{})

def retire_packaged_mirrors(runtime,source,previous,logs):
    """Retire recorded distribution copies after the canonical copy exists."""
    for name in ('external_skills.py','skills_registry.py'):
        relative='template/scripts/harness/'+name;path=runtime/relative
        if not path.exists() and not path.is_symlink():continue
        if any(p.is_symlink() for p in (path,*path.parents) if p==runtime or runtime in p.parents) or not path.is_file():
            logs.append('PRESERVED unsafe packaging mirror: '+str(path));continue
        canonical=runtime/name
        if not canonical.is_file() or canonical.is_symlink() or canonical.read_bytes()!=resolve_runtime_asset(source,name).read_bytes():
            logs.append('PRESERVED mirror: canonical runtime customized or missing: '+str(path));continue
        raw=path.read_bytes()
        if hashlib.sha256(raw).hexdigest()!=previous.get(relative):
            logs.append('PRESERVED customized packaging mirror: '+str(path));continue
        backup=runtime/'retired-assets'/relative
        if any(p.is_symlink() for p in (backup,*backup.parents) if p==runtime or runtime in p.parents):raise ValueError('Unsafe packaging mirror backup')
        if backup.exists() and backup.read_bytes()!=raw:raise ValueError('Conflicting packaging mirror backup')
        if not backup.exists():
            from aikya.storage import atomic_write
            atomic_write(backup,raw)
        path.unlink();previous.pop(relative,None)
        logs.append('RETIRED managed packaging mirror with backup: '+str(path))


def register_startup_hook(settings:Path, command:str, logs:list[str]) -> None:
    """Merge a lightweight project-discovery hook without clobbering user settings."""
    if settings.is_symlink():
        logs.append(f'NOTICE: symlinked configuration preserved: {settings}')
        return
    try:
        user=json.loads(settings.read_text(encoding='utf8')) if settings.exists() else {}
        if not isinstance(user,dict) or not isinstance(user.get('hooks',{}),dict):
            raise ValueError('invalid settings')
    except (ValueError,UnicodeError,OSError):
        logs.append(f'NOTICE: invalid settings; install hook manually: {settings}')
        return
    hooks=user.setdefault('hooks',{})
    session=hooks.setdefault('SessionStart',[])
    if not isinstance(session,list):
        logs.append(f'NOTICE: invalid hooks.SessionStart: {settings}')
        return
    # Avoid hook duplication when setup runs twice.
    if not any('aikya_session.py' in str(h.get('command',''))
               for group in session if isinstance(group,dict)
               for h in group.get('hooks',[]) if isinstance(h,dict)):
        session.append({'matcher':'startup','hooks':[command if isinstance(command,dict) else {'type':'command','command':command,'timeout':5}]})
        settings.parent.mkdir(parents=True,exist_ok=True)
        settings.write_text(json.dumps(user,indent=2,ensure_ascii=False)+'\n',encoding='utf8')
        logs.append(f'SessionStart hook added: {settings}')


# Remove older command assets only when they exactly match the managed historical template.
# Never implicitly delete a user-modified skill.
from aikya.cli.commands import LEGACY_RENAMES

def command_retirement_plan(skill_root: Path, runtime: Path) -> list[dict]:
    """Preview verified retirement. Unknown user edits remain active for manual review."""
    from aikya.documentation.migration_hashes import ASSETS
    result=[]
    for name,replacement in LEGACY_RENAMES.items():
        legacy=skill_root/name/'SKILL.md'
        if not legacy.exists() and not legacy.is_symlink():continue
        backup=runtime/'command-backups'/name/'SKILL.md'
        if any(p.is_symlink() for p in (legacy,legacy.parent)):
            result.append({'path':legacy,'replacement':replacement,'action':'PRESERVE_CUSTOM_COMMAND'});continue
        if not legacy.is_file():raise ValueError('Non-regular legacy command requires review')
        record=ASSETS.get('.claude/skills/'+name+'/SKILL.md',{})
        digest=hashlib.sha256(legacy.read_bytes()).hexdigest()
        verified=digest==record.get('sha256') or digest in record.get('variants',{})
        older=runtime/'bootstrap_skills'/name/'SKILL.md'
        if not verified and not record and older.is_file() and not any(p.is_symlink() for p in (older,*older.parents) if p==runtime or runtime in p.parents):verified=legacy.read_bytes()==older.read_bytes()
        if not verified:
            result.append({'path':legacy,'replacement':replacement,'action':'PRESERVE_CUSTOM_COMMAND'});continue
        if any(p.is_symlink() for p in (backup,*backup.parents) if p==runtime or runtime in p.parents):raise ValueError('Symlinked command retirement backup')
        if backup.exists() and (not backup.is_file() or backup.read_bytes()!=legacy.read_bytes()):raise ValueError('Existing command backup differs; review before retirement')
        result.append({'path':legacy,'replacement':replacement,'backup':backup,'sha256':digest,'action':'RETIRE_VERIFIED_COMMAND'})
    return result

def retire_legacy_commands(skill_root: Path, runtime: Path, logs: list[str], operations: list[dict] | None = None) -> None:
    operations=command_retirement_plan(skill_root,runtime) if operations is None else operations
    # A backup alone is not a usable replacement. Validate the whole batch first.
    for op in operations:
        if op['action']!='RETIRE_VERIFIED_COMMAND':continue
        replacement=skill_root/op['replacement']/'SKILL.md'
        if replacement.is_symlink() or replacement.parent.is_symlink() or not replacement.is_file():
            raise ValueError(f'Replacement command is not available: {replacement}')
    for op in operations:
        legacy=op['path'];name=legacy.parent.name
        if op['action']=='PRESERVE_CUSTOM_COMMAND':
            logs.append(f'PRESERVED old customized command /{name}; review migration to /{op["replacement"]}');continue
        if hashlib.sha256(legacy.read_bytes()).hexdigest()!=op['sha256']:raise ValueError('Legacy command changed since preflight')
        backup=op['backup'];backup.parent.mkdir(parents=True,exist_ok=True)
        if not backup.exists():shutil.copy2(legacy,backup)
        legacy.unlink()
        try:legacy.parent.rmdir()
        except OSError:pass
        logs.append(f'RETIRADO comando gestionado antiguo /{name}; sustituido por /{op["replacement"]}; backup={backup}')

def migrate_legacy_runtime_skills(runtime: Path, previous: dict[str, str], logs: list[str]) -> None:
    """Remove only verifiably managed skills from the former runtime directory.

    The active commands in .claude/skills are NOT moved or deleted here.
    Customized, untracked and symlinked legacy files are preserved.
    """
    legacy_root = runtime / 'bootstrap_skills'
    if not legacy_root.exists() and not legacy_root.is_symlink():
        return
    if legacy_root.is_symlink() or not legacy_root.is_dir():
        logs.append(f'PRESERVED non-regular legacy directory: {legacy_root}')
        return
    for name in sorted(set(BOOTSTRAP_COMMANDS) | set(LEGACY_RENAMES)):
        folder = legacy_root / name
        skill = folder / 'SKILL.md'
        if folder.is_symlink() or not folder.is_dir() or skill.is_symlink() or not skill.is_file():
            continue
        key = skill.relative_to(runtime).as_posix()
        recorded = previous.get(key)
        raw = skill.read_bytes()
        if not recorded or hashlib.sha256(raw).hexdigest() != recorded or b'AIKYA BOOTSTRAP MANAGED' not in raw:
            logs.append(f'PRESERVED customized or unverified legacy asset: {skill}')
            continue
        # Do not remove an entire folder if it contains other user files.
        skill.unlink()
        previous.pop(key, None)
        try:
            folder.rmdir()
        except OSError:
            pass
        logs.append(f'MIGRADO a aikya-skills/ (runtime anterior retirado): {skill}')
    try:
        legacy_root.rmdir()
    except OSError:
        logs.append(f'PRESERVED additional legacy content: {legacy_root}')


def managed_bootstrap_settings(root):
    marker=root/'.aikya/bootstrap.json';settings=root/'.claude/settings.json'
    if any(p.is_symlink() for p in (marker,marker.parent,settings,settings.parent)):return False
    try:
        data=json.loads(marker.read_text())
        return data.get('_generated_by')=='aikya-setup' and data.get('managed_settings_sha256')==hashlib.sha256(settings.read_bytes()).hexdigest()
    except (ValueError,OSError,AttributeError):return False

def setup(source:Path,target:Path,scope:str,home:Path|None=None,dry_run:bool=False,subagent_statusline:bool=False)->list[str]:
    source=source.resolve()
    target=target.expanduser().resolve()
    home=(home or Path.home()).expanduser().resolve()
    if scope not in ('global','project'):raise ValueError('scope debe ser global o project')
    if any(not (source_path(source,'aikya-skills')/name/'SKILL.md').is_file() for name in BOOTSTRAP_COMMANDS):
        raise ValueError('Source is not a complete Aikya distribution')
    runtime=(home/'.claude/aikya-harnes') if scope=='global' else (target/'.aikya/runtime')
    skill_root=(home/'.claude/skills') if scope=='global' else (target/'.claude/skills')
    for candidate in (runtime, runtime.parent, skill_root, skill_root.parent):
        if candidate.is_symlink():
            raise ValueError(f'Symlinked directories are not supported: {candidate}')
    settings_path=(home if scope=='global' else target)/'.claude/settings.json'
    settings_created=not settings_path.exists()
    settings_owned=managed_bootstrap_settings(target) if scope=='project' else False
    for name in BOOTSTRAP_COMMANDS:
        destination=skill_root/name/'SKILL.md'
        if destination.is_symlink() or destination.parent.is_symlink() or (destination.exists() and not destination.is_file()):
            raise ValueError(f'Invalid or symlinked skill destination: {destination}')
    retirement=command_retirement_plan(skill_root,runtime)
    operations=list(files_to_copy(source))
    from aikya.installation.runtime import prepare_bundle, apply_bundle
    bundle=prepare_bundle(runtime,source,'registration')
    logs=[f'AIKYA SCOPE={scope} runtime={runtime} skills={skill_root}']
    if dry_run:
        logs.extend('PLAN: '+op['action']+' /'+op['path'].parent.name+' -> /'+op['replacement'] for op in retirement)
        logs.append(f'PLAN: {len(operations)} runtime files and {len(BOOTSTRAP_COMMANDS)} skills; no interview or external download')
        return logs
    runtime.mkdir(parents=True,exist_ok=True)
    apply_bundle(runtime,bundle,logs)
    old_manifest={}
    if (runtime/'manifest.json').is_file():
        try:
            old_manifest=json.loads((runtime/'manifest.json').read_text(encoding='utf8')).get('files',{})
            if not isinstance(old_manifest, dict):
                old_manifest={}
        except (ValueError,OSError):
            old_manifest={}
    migrate_legacy_runtime_skills(runtime,old_manifest,logs)
    new_manifest=dict(old_manifest)
    for src,rel in operations:
        dst=runtime/rel
        managed_copy(src,dst,runtime,logs)
        written=dst.read_bytes()
        if written==runtime_asset_bytes(rel,src.read_bytes()):
            new_manifest[rel.as_posix()]=hashlib.sha256(written).hexdigest()
    retire_packaged_mirrors(runtime,source,new_manifest,logs)
    retire_historical_gallery(runtime,new_manifest,logs)
    (runtime/'manifest.json').write_text(json.dumps({'_generated_by':'aikya-setup','files':new_manifest},indent=2)+'\n',encoding='utf8')
    for name in BOOTSTRAP_COMMANDS:
        src=source_path(source,'aikya-skills')/name/'SKILL.md'
        dst=skill_root/name/'SKILL.md'
        if dst.is_symlink() or dst.parent.is_symlink():
            raise ValueError(f'Symlinked skill is not allowed: {dst}')
        rendered=asset_bytes(dst,src.read_bytes())
        if dst.exists() and dst.read_bytes()!=rendered:
            # Only replace our own previous generated bootstrap skills.
            if not verified_skill_upgrade(dst,src,old_manifest.get('aikya-skills/'+name+'/SKILL.md')):
                logs.append(f'PRESERVED customized skill: {dst}')
                continue
        dst.parent.mkdir(parents=True,exist_ok=True)
        dst.write_bytes(rendered)
        shutil.copymode(src,dst) if isinstance(src,Path) else None
        logs.append(f'SKILL disponible: /{name} ({scope})')
    python = Path(sys.executable).absolute()
    shell = host_shell()
    command = render_managed_hook(python, runtime / 'aikya_session.py', (), shell)
    register_startup_hook(settings_path, command, logs)
    from aikya.middleware.configuration import register_visibility
    observer = render_managed_hook(python, runtime / 'execution_observer.py', ('hook',), shell)
    bar = status_command(python, runtime / 'aikya_statusline.py', shell)
    subagent = status_command(python, runtime / 'aikya_subagent_statusline.py', shell) if subagent_statusline else None
    register_visibility(settings_path, observer, bar, logs, (home / '.claude' if scope == 'global' else target / '.aikya') / 'visibility-proposed.json', subagent_command=subagent)
    if scope=='project':
        marker=target/'.aikya/bootstrap.json'
        marker.parent.mkdir(parents=True,exist_ok=True)
        if not marker.exists() or settings_created or settings_owned:
            if marker.is_symlink():raise ValueError('Symlinked bootstrap marker')
            payload={'_generated_by':'aikya-setup','scope':'project','runtime':'.aikya/runtime'}
            if settings_created or settings_owned:payload['managed_settings_sha256']=hashlib.sha256(settings_path.read_bytes()).hexdigest()
            marker.write_text(json.dumps(payload,indent=2)+'\n',encoding='utf8')
    retire_legacy_commands(skill_root,runtime,logs,retirement)
    return logs


def main(argv=None):
    p=argparse.ArgumentParser(description='Aikya Harness registration within Claude Code')
    p.add_argument('--scope',choices=['global','project'],required=True)
    p.add_argument('--target',type=Path,default=Path.cwd(),help='Directorio de trabajo actual, cuando scope=project')
    p.add_argument('--subagent-statusline',action='store_true',help='Enable only on a client supporting subagentStatusLine')
    p.add_argument('--dry-run',action='store_true')
    args=p.parse_args(argv)
    try:
        for line in setup(ROOT,args.target,args.scope,dry_run=args.dry_run,subagent_statusline=args.subagent_statusline): print(line)
    except (OSError,ValueError) as exc:
        print(f'ERROR: {exc}',file=sys.stderr)
        return 1
    print('Next: in Claude Code use /aikya-init (nuevo), /aikya-analyze (existente), /aikya-answers, /aikya-scaffold, /aikya-skills-status o /aikya-quality.')
    return 0

if __name__=='__main__':sys.exit(main())
